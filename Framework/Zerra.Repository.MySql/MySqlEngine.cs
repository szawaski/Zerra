        private bool AssureTable(bool create, List<string> sql, bool needCreateDatabase, ModelDetail model)
        {
            var nonIdentityColumns = model.Members.Where(x => !x.IsIdentity && !x.IsDataSourceEntity && x.ColumnCoreType.HasValue || x.Type == typeof(byte[])).ToArray();
            var identityColumns = model.Members.Where(x => x.IsIdentity).ToArray();

            if (nonIdentityColumns.Length + identityColumns.Length == 0)
                return false; //Cannot create table with no columns

            if (!needCreateDatabase)
            {
                var sqlQuery = $"SELECT COUNT(1) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_SCHEMA = DATABASE() AND LOWER(TABLE_NAME) = '{model.DataSourceEntityName.ToLower()}'";
                var exists = ExecuteSqlScalar<long>(sqlQuery) > 0;
                if (exists)
                    return false;
            }
            if (create)
            {
                var sb = new StringBuilder();
                _ = sb.Append("CREATE TABLE ").Append(model.DataSourceEntityName).Append("(\r\n");

                for (var i = 0; i < identityColumns.Length; i++)
                {
                    var property = identityColumns[i];
                    if (i > 0)
                        _ = sb.Append(",\r\n");
                    _ = sb.Append("\t`").Append(property.StoreName).Append("` ");
                    WriteSqlTypeFromModel(sb, property);
                }
                for (var i = 0; i < nonIdentityColumns.Length; i++)
                {
                    var property = nonIdentityColumns[i];
                    if (i > 0 || identityColumns.Length > 0)
                        _ = sb.Append(",\r\n");
                    _ = sb.Append("\t`").Append(property.StoreName).Append("` ");
                    WriteSqlTypeFromModel(sb, property);
                }


                if (identityColumns.Length > 0)
                {
                    if (identityColumns.Length > 0 || nonIdentityColumns.Length > 0)
                        _ = sb.Append(',');
                    _ = sb.Append("\r\n\tCONSTRAINT PK_").Append(model.DataSourceEntityName).Append(" PRIMARY KEY(\r\n");

                    //MySql must have AutoGenerated first
                    identityColumns = identityColumns.OrderByDescending(x => x.IsIdentityAutoGenerated).ToArray();
                    for (var i = 0; i < identityColumns.Length; i++)
                    {
                        var property = identityColumns[i];
                        if (i > 0)
                            _ = sb.Append(",\r\n");
                        _ = sb.Append("\t\t`").Append(property.StoreName).Append('`');
                    }
                    _ = sb.Append("\r\n\t)\r\n");
                }
                _ = sb.Append("\r\n)");

                sql.Add(sb.ToString());
            }
            return true;
        }

        private void AssureColumns(bool create, bool update, bool delete, List<string> sql, ModelDetail model, SqlColumnType[] sqlColumns, SqlConstraint[] sqlConstraints, HashSet<string> droppedConstraints)
        {
            var columns = model.Members.Where(x => !x.IsDataSourceEntity && x.ColumnCoreType.HasValue || x.Type == typeof(byte[])).ToArray();

            var sb = new StringBuilder();

            foreach (var column in columns)
            {
                var sqlColumn = sqlColumns.FirstOrDefault(x => String.Equals(x.Table, model.DataSourceEntityName, StringComparison.OrdinalIgnoreCase) && x.Column == column.StoreName);
                if (sqlColumn is null)
                {
                    if (create)
                    {
                        _ = sb.Append("ALTER TABLE `").Append(model.DataSourceEntityName).Append("` ADD `").Append(column.StoreName).Append("` ");
                        WriteSqlTypeFromModel(sb, column);
                        var withDefault = column.IsDataSourceNotNull && !column.IsIdentityAutoGenerated;
                        if (withDefault)
                        {
                            _ = sb.Append(" DEFAULT ");
                            WriteDefaultValue(sb, column);
                        }
                        _ = sb.Append(';');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                        if (withDefault)
                        {
                            _ = sb.Append("ALTER TABLE `").Append(model.DataSourceEntityName).Append("` ALTER COLUMN `").Append(column.StoreName).Append("` DROP DEFAULT;");
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }
                    }
                }
                else
                {
                    if (update)
                    {
                        var sameType = ModelMatchesSqlType(column, sqlColumn);
                        if (!sameType)
                        {
                            if (sqlColumn.IsPrimaryKey || sqlColumn.IsAutoGenerated || sqlColumn.IsPrimaryKey != column.IsIdentity || sqlColumn.IsAutoGenerated != column.IsIdentityAutoGenerated)
                                throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MySqlEngine)} cannot automatically change column with a Primary Key or Identity {model.Type.Name}.{column.Name}");

                            var theseSqlConstraints = sqlConstraints.Where(x => (String.Equals(x.PK_Table, model.DataSourceEntityName, StringComparison.OrdinalIgnoreCase) && x.PK_Column == column.Name) || (String.Equals(x.FK_Table, model.DataSourceEntityName, StringComparison.OrdinalIgnoreCase) && x.FK_Column == column.Name)).ToArray();
                            if (theseSqlConstraints.Length > 0)
                            {
                                foreach (var sqlConstraint in theseSqlConstraints)
                                {
                                    if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                                        continue;
                                    _ = sb.Append("ALTER TABLE `").Append(sqlConstraint.FK_Table).Append("` DROP CONSTRAINT `").Append(sqlConstraint.FK_Name).Append("`;");
                                    sql.Add(sb.ToString());
                                    _ = sb.Clear();
                                }
                            }

                            _ = sb.Append("ALTER TABLE `").Append(model.DataSourceEntityName).Append("` MODIFY `").Append(column.StoreName).Append("` ");
                            WriteSqlTypeFromModel(sb, column);
                            _ = sb.Append(';');
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }
                    }
                }
            }

            if (delete)
            {
                //columns not in model
                foreach (var sqlColumn in sqlColumns.Where(x => String.Equals(x.Table, model.DataSourceEntityName, StringComparison.OrdinalIgnoreCase)))
                {
                    var column = columns.FirstOrDefault(x => x.StoreName == sqlColumn.Column);
                    if (column is null)
                    {
                        var theseSqlConstraints = sqlConstraints.Where(x => (x.PK_Table == sqlColumn.Table && x.PK_Column == sqlColumn.Column) || (x.FK_Table == sqlColumn.Table && x.FK_Column == sqlColumn.Column)).ToArray();
                        if (theseSqlConstraints.Length > 0)
                        {
                            foreach (var sqlConstraint in theseSqlConstraints)
                            {
                                if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                                    continue;
                                _ = sb.Append("ALTER TABLE `").Append(sqlConstraint.FK_Table).Append("` DROP CONSTRAINT `").Append(sqlConstraint.FK_Name).Append("`;");
                                sql.Add(sb.ToString());
                                _ = sb.Clear();
                            }
                        }

                        if (!sqlColumn.IsNullable)
                        {
                            if (sqlColumn.IsPrimaryKey || sqlColumn.IsAutoGenerated)
                                throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MySqlEngine)} needs to make {sqlColumn.Table}.{sqlColumn.Column} nullable but cannot automatically change column with a Primary Key or Identity");

                            _ = sb.Append("ALTER TABLE `").Append(model.DataSourceEntityName).Append("` MODIFY `").Append(sqlColumn.Column).Append("` ");
                            WriteSqlTypeFromColumnAsNullable(sb, sqlColumn);
                            _ = sb.Append(';');
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }
                    }
                }
            }
        }

        private void AssureConstraints(bool create, bool update, bool delete, List<string> sql, ModelDetail model, SqlConstraint[] sqlConstraints, HashSet<string> droppedConstraints)
        {
            var constraintNameDictionary = sqlConstraints.Select(x => x.FK_Name).Distinct(StringComparer.OrdinalIgnoreCase).ToDictionary(x => x, x => 0, StringComparer.OrdinalIgnoreCase);

            var sb = new StringBuilder();

            var fkTable = model.DataSourceEntityName;

            var usedSqlConstraints = new List<SqlConstraint>();
            foreach (var columnForRelation in model.RelatedNonEnumerableMembers)
            {
                var relatedModelDetails = ModelAnalyzer.GetModel(columnForRelation.ActualType);

                if (columnForRelation.ForeignIdentities is null)
                    throw new Exception($"{columnForRelation.Type.Name} missing Foreign Identity");

                //a key of several members is one constraint of its columns, in the order of the identity referred to

                if (columnForRelation.ForeignIdentities!.Length != relatedModelDetails.IdentityMembers.Count)

                    throw new Exception($"{columnForRelation.Name} names {columnForRelation.ForeignIdentities.Length} foreign identities where {relatedModelDetails.Type.Name} has {relatedModelDetails.IdentityMembers.Count} identities");

                var fkColumns = columnForRelation.ForeignIdentities.Select(x => model.GetMember(x).StoreName).ToArray();

                var pkTable = relatedModelDetails.DataSourceEntityName;

                var pkColumns = relatedModelDetails.IdentityMembers.Select(x => x.StoreName).ToArray();

                var fkColumn = String.Join(",", fkColumns);

                var pkColumn = String.Join(",", pkColumns);


                var constraintColumns = sqlConstraints.Where(x => String.Equals(x.FK_Table, fkTable, StringComparison.OrdinalIgnoreCase) && String.Equals(x.PK_Table, pkTable, StringComparison.OrdinalIgnoreCase)).GroupBy(x => x.FK_Name).FirstOrDefault(x => x.Count() == fkColumns.Length && x.Select((column, index) => String.Equals(column.FK_Column, fkColumns[index], StringComparison.OrdinalIgnoreCase) && String.Equals(column.PK_Column, pkColumns[index], StringComparison.OrdinalIgnoreCase)).All(match => match))?.ToArray();

                var sqlConstraint = constraintColumns?[0];
                if (sqlConstraint is null || droppedConstraints.Contains(sqlConstraint.FK_Name))
                {
                    if (create)
                    {
                        var baseConstraintName = $"FK_{fkTable}_{pkTable}";
                        string constraintName;
                        if (sqlConstraint is not null)
                        {
                            constraintName = sqlConstraint.FK_Name;
                        }
                        else if (constraintNameDictionary.TryGetValue(baseConstraintName, out var constraintNameIndex))
                        {
                            constraintNameIndex++;
                            constraintName = baseConstraintName + constraintNameIndex;
                            while (constraintNameDictionary.ContainsKey(constraintName))
                            {
                                constraintNameIndex++;
                                constraintName = baseConstraintName + constraintNameIndex;
                            }
                            constraintNameDictionary[constraintName] = constraintNameIndex;
                        }
                        else
                        {
                            constraintNameDictionary.Add(baseConstraintName, 0);
                            constraintName = baseConstraintName;
                        }
                        _ = sb.Append("ALTER TABLE `").Append(fkTable).Append("` ADD CONSTRAINT ").Append(constraintName).Append(" FOREIGN KEY (").Append(fkColumn).Append(") REFERENCES `").Append(pkTable).Append("`(").Append(pkColumn).Append(");");
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }
                }
                else
                {
                    usedSqlConstraints.AddRange(constraintColumns!);
                }
            }

            if (delete)
            {
                //foreign keys not in model
                foreach (var sqlConstraint in sqlConstraints.Where(x => x.FK_Table == fkTable).GroupBy(x => x.FK_Name).Select(x => x.First()))
                {
                    if (!usedSqlConstraints.Any(x => x.FK_Name == sqlConstraint.FK_Name) && !droppedConstraints.Contains(sqlConstraint.FK_Name))
                    {
                        _ = sb.Append("ALTER TABLE `").Append(sqlConstraint.FK_Table).Append("` DROP CONSTRAINT ").Append(sqlConstraint.FK_Name).Append(';');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }
                }
            }
        }

        private void AssureIndexes(bool create, bool update, bool delete, List<string> sql, ModelDetail model, SqlIndex[] sqlIndexes)
        {
            var sb = new StringBuilder();

            var usedSqlIndexes = new List<SqlIndex>();
            foreach (var index in model.Indexes)
            {
                var sqlIndex = sqlIndexes.FirstOrDefault(x => String.Equals(x.Name, index.StoreName, StringComparison.OrdinalIgnoreCase));
                if (sqlIndex is not null)
                {
                    usedSqlIndexes.Add(sqlIndex);
                    var matches = sqlIndex.IsUnique == index.IsUnique && sqlIndex.Columns.Count == index.Members.Count;
                    for (var i = 0; matches && i < index.Members.Count; i++)
                        matches = String.Equals(sqlIndex.Columns[i], index.Members[i].StoreName, StringComparison.OrdinalIgnoreCase) && sqlIndex.Descending[i] == index.Descending[i];
                    if (matches || !update)
                        continue;

                    //one statement so a foreign key using the index is never without one
                    _ = sb.Append("ALTER TABLE `").Append(model.DataSourceEntityName).Append("` DROP INDEX `").Append(sqlIndex.Name).Append(index.IsUnique ? "`, ADD UNIQUE INDEX `" : "`, ADD INDEX `").Append(index.StoreName).Append('`');
                }
                else if (create)
                {
                    _ = sb.Append(index.IsUnique ? "CREATE UNIQUE INDEX `" : "CREATE INDEX `").Append(index.StoreName).Append("` ON `").Append(model.DataSourceEntityName).Append('`');
                }
                else
                {
                    continue;
                }

                _ = sb.Append('(');
                for (var i = 0; i < index.Members.Count; i++)
                {
                    if (i > 0)
                        _ = sb.Append(", ");
                    _ = sb.Append('`').Append(index.Members[i].StoreName).Append('`');
                    if (index.Descending[i])
                        _ = sb.Append(" DESC");
                }
                _ = sb.Append(");");
                sql.Add(sb.ToString());
                _ = sb.Clear();
            }

            if (delete)
            {
                //indexes not in model, MySql keeps an index on each foreign key
                foreach (var sqlIndex in sqlIndexes)
                {
                    if (usedSqlIndexes.Contains(sqlIndex) || model.RelatedNonEnumerableMembers.Any(x => x.ForeignIdentities!.Contains(sqlIndex.Columns[0], StringComparer.OrdinalIgnoreCase)))
                        continue;
                    _ = sb.Append("DROP INDEX `").Append(sqlIndex.Name).Append("` ON `").Append(model.DataSourceEntityName).Append("`;");
                    sql.Add(sb.ToString());
                    _ = sb.Clear();
                }
            }
        }

        /// <summary>
        /// Writes the MySQL column type definition for a model property into the provided <see cref="StringBuilder"/>.
        /// </summary>
        /// <param name="sb">The <see cref="StringBuilder"/> to write the type definition into.</param>
        /// <param name="property">The model property to derive the SQL type from.</param>
        public static void WriteSqlTypeFromModel(StringBuilder sb, ModelMemberDetail property)
        {
            var canBeIdentity = false;
            if (property.ColumnCoreType.HasValue)
            {
                switch (property.ColumnCoreType.Value)
                {
                    case CoreType.Boolean:
                    case CoreType.BooleanNullable:
                        _ = sb.Append("bit");
                        break;
                    case CoreType.Byte:
                    case CoreType.ByteNullable:
                        _ = sb.Append("tinyint");
                        canBeIdentity = true;
                        break;
                    case CoreType.Int16:
                    case CoreType.Int16Nullable:
                        _ = sb.Append("smallint");
                        canBeIdentity = true;
                        break;
                    case CoreType.Int32:
                    case CoreType.Int32Nullable:
                        _ = sb.Append("int");
                        canBeIdentity = true;
                        break;
                    case CoreType.Int64:
                    case CoreType.Int64Nullable:
                        _ = sb.Append("bigint");
                        canBeIdentity = true;
                        break;
                    case CoreType.Single:
                    case CoreType.SingleNullable:
                        _ = sb.Append("float");
                        break;
                    case CoreType.Double:
                    case CoreType.DoubleNullable:
                        _ = sb.Append("real");
                        break;
                    case CoreType.Decimal:
                    case CoreType.DecimalNullable:
                        _ = sb.Append("decimal(").Append(property.DataSourcePrecisionLength ?? 19).Append(", ").Append(property.DataSourceScale ?? 5).Append(')');
                        canBeIdentity = property.DataSourceScale == 0;
                        break;
                    case CoreType.Char:
                    case CoreType.CharNullable:
                        _ = sb.Append("varchar(").Append(property.DataSourcePrecisionLength ?? 1).Append(')');
                        break;
                    case CoreType.DateTime:
                    case CoreType.DateTimeNullable:
                        if (property.DatePart == StoreDatePart.Date)
                            _ = sb.Append("date");
                        else
                            _ = sb.Append("datetime(").Append(property.DataSourcePrecisionLength ?? 6).Append(')');
                        break;
                    case CoreType.DateTimeOffset:
                    case CoreType.DateTimeOffsetNullable:
                        _ = sb.Append("datetime(").Append(property.DataSourcePrecisionLength ?? 6).Append(')');
                        break;
                    case CoreType.TimeSpan:
                    case CoreType.TimeSpanNullable:
                        _ = sb.Append("time(").Append(property.DataSourcePrecisionLength ?? 6).Append(')');
                        break;
                    case CoreType.DateOnly:
                    case CoreType.DateOnlyNullable:
                        _ = sb.Append("date");
                        break;
                    case CoreType.TimeOnly:
                    case CoreType.TimeOnlyNullable:
                        _ = sb.Append("time(").Append(property.DataSourcePrecisionLength ?? 6).Append(')');
                        break;
                    case CoreType.Guid:
                    case CoreType.GuidNullable:
                        _ = sb.Append("binary(16)");
                        canBeIdentity = true;
                        break;
                    case CoreType.String:
                        if (property.DataSourcePrecisionLength.HasValue)
                            _ = sb.Append("varchar(").Append(property.DataSourcePrecisionLength.Value).Append(')');
                        else
                            _ = sb.Append("text");
                        break;
                    default:
                        throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MySqlEngine)} type.");
                }
            }
            else if (property.Type == typeof(byte[]))
            {
                if (property.DataSourcePrecisionLength.HasValue)
                    _ = sb.Append("varbinary(").Append(property.DataSourcePrecisionLength.Value).Append(')');
                else
                    _ = sb.Append("blob");
            }
            else
            {
                throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MySqlEngine)} type.");
            }

            if (property.IsDataSourceNotNull) //model checks for identity not null
            {
                _ = sb.Append(" NOT NULL");
                //if (property.IsIdentity && !property.IsIdentityAutoGenerated)
                //{
                //    _ = sb.Append(" DEFAULT (");
                //    WriteDefaultValue(sb, property);
                //    _ = sb.Append(')');
                //}
            }
            else
            {
                _ = sb.Append(" NULL");
            }

            if (property.IsIdentity && property.IsIdentityAutoGenerated)
            {
                if (!canBeIdentity)
                    throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MySqlEngine)} {property.Type.Name} {property.Name} cannot be an auto generated identity");
                if (property.CoreType.HasValue && property.CoreType == CoreType.Guid)
                    throw new NotSupportedException("MySQL does not support auto generated GUIDs as identities.");
                else
                    _ = sb.Append(" AUTO_INCREMENT");
            }
        }

        private static void WriteDefaultValue(StringBuilder sb, ModelMemberDetail property)
        {
            _ = sb.Append('(');
            if (property.ColumnCoreType.HasValue)
            {
                switch (property.ColumnCoreType.Value)
                {
                    case CoreType.Byte:
                    case CoreType.ByteNullable:
                    case CoreType.SByte:
                    case CoreType.SByteNullable:
                    case CoreType.Int16:
                    case CoreType.Int16Nullable:
                    case CoreType.UInt16:
                    case CoreType.UInt16Nullable:
                    case CoreType.Int32:
                    case CoreType.Int32Nullable:
                    case CoreType.UInt32:
                    case CoreType.UInt32Nullable:
                    case CoreType.Int64:
                    case CoreType.Int64Nullable:
                    case CoreType.UInt64:
                    case CoreType.UInt64Nullable:
                    case CoreType.Single:
                    case CoreType.SingleNullable:
                    case CoreType.Double:
                    case CoreType.DoubleNullable:
                    case CoreType.Decimal:
                    case CoreType.DecimalNullable:
                        _ = sb.Append('0');
                        break;
                    case CoreType.Boolean:
                    case CoreType.BooleanNullable:
                        _ = sb.Append('0');
                        break;
                    case CoreType.Char:
                    case CoreType.CharNullable:
                    case CoreType.String:
                        _ = sb.Append('\'').Append(property.EnumDefaultText?.Replace("\\", "\\\\").Replace("'", "''")).Append('\'');
                        break;
                    case CoreType.DateTime:
                    case CoreType.DateTimeNullable:
                    case CoreType.DateOnly:
                    case CoreType.DateOnlyNullable:
                        _ = sb.Append("'1900-01-01'");
                        break;
                    case CoreType.DateTimeOffset:
                    case CoreType.DateTimeOffsetNullable:
                        _ = sb.Append("'1900-01-01'");
                        break;
                    case CoreType.TimeSpan:
                    case CoreType.TimeSpanNullable:
                    case CoreType.TimeOnly:
                    case CoreType.TimeOnlyNullable:
                        _ = sb.Append("'00:00:00'");
                        break;
                    case CoreType.Guid:
                    case CoreType.GuidNullable:
                        _ = sb.Append("0x00000000000000000000000000000000");
                        break;
                    default:
                        throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MySqlEngine)} type.");
                }
            }
            else if (property.Type == typeof(byte[]))
            {
                _ = sb.Append("X''");
            }
            else
            {
                throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MySqlEngine)} type.");
            }
            _ = sb.Append(')');
        }

        private static void WriteSqlTypeFromColumnAsNullable(StringBuilder sb, SqlColumnType sqlColumn)
        {
            switch (sqlColumn.DataType)
            {
                case "bit":
                case "tinyint":
                case "smallint":
                case "int":
                case "bigint":
                case "real":
                case "float":
                case "double":

                case "date":

                case "text":
                case "blob":
                    _ = sb.Append(sqlColumn.DataType);
                    break;
                case "numeric":
                case "decimal":
                    _ = sb.Append(sqlColumn.DataType).Append('(').Append(sqlColumn.NumericPrecision ?? 0).Append(", ").Append(sqlColumn.NumericScale ?? 0).Append(')');
                    break;
                case "datetime":
                case "time":
                    _ = sb.Append(sqlColumn.DataType).Append('(').Append(sqlColumn.DatetimePrecision ?? 0).Append(')');
                    break;
                case "varchar":
                case "nvarchar":
                case "char":
                case "nchar":
                case "binary":
                case "varbinary":
                    _ = sb.Append(sqlColumn.DataType).Append('(').Append(!sqlColumn.CharacterMaximumLength.HasValue || sqlColumn.CharacterMaximumLength.Value == -1 ? "max" : sqlColumn.CharacterMaximumLength.Value.ToString()).Append(')');
                    break;
                default:
                    throw new NotImplementedException($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MySqlEngine)} type {sqlColumn.DataType} not implemented.");
            }

            _ = sb.Append(" NULL");
        }

        private static bool ModelMatchesSqlType(ModelMemberDetail property, SqlColumnType sqlColumn)
        {
            if (sqlColumn.IsPrimaryKey != property.IsIdentity || sqlColumn.IsAutoGenerated != property.IsIdentityAutoGenerated)
                return false;

            if (property.ColumnCoreType.HasValue)
            {
                switch (property.ColumnCoreType.Value)
                {
                    case CoreType.Boolean: return sqlColumn.DataType == "bit" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Byte: return sqlColumn.DataType == "tinyint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int16: return sqlColumn.DataType == "smallint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int32: return sqlColumn.DataType == "int" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int64: return sqlColumn.DataType == "bigint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Single: return sqlColumn.DataType == "float" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Double: return sqlColumn.DataType == "double" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Decimal: return sqlColumn.DataType == "decimal" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.NumericPrecision == (property.DataSourcePrecisionLength ?? 19) && sqlColumn.NumericScale == (property.DataSourceScale ?? 5);
                    case CoreType.Char: return sqlColumn.DataType == "varchar" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.CharacterMaximumLength == (property.DataSourcePrecisionLength ?? 1);
                    case CoreType.DateTime: return ((sqlColumn.DataType == "datetime" && property.DatePart == StoreDatePart.DateTime && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6)) || (sqlColumn.DataType == "date" && property.DatePart == StoreDatePart.Date)) && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.DateTimeOffset: return sqlColumn.DataType == "datetime" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6);
                    case CoreType.TimeSpan: return sqlColumn.DataType == "time" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6);
                    case CoreType.DateOnly: return sqlColumn.DataType == "date" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.TimeOnly: return sqlColumn.DataType == "time" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6);
                    case CoreType.Guid: return sqlColumn.DataType == "binary" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;

                    case CoreType.BooleanNullable: return sqlColumn.DataType == "bit" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.ByteNullable: return sqlColumn.DataType == "tinyint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int16Nullable: return sqlColumn.DataType == "smallint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int32Nullable: return sqlColumn.DataType == "int" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int64Nullable: return sqlColumn.DataType == "bigint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.SingleNullable: return sqlColumn.DataType == "float" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.DoubleNullable: return sqlColumn.DataType == "double" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.DecimalNullable: return sqlColumn.DataType == "decimal" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.NumericPrecision == (property.DataSourcePrecisionLength ?? 19) && sqlColumn.NumericScale == (property.DataSourceScale ?? 5);
                    case CoreType.CharNullable: return sqlColumn.DataType == "varchar" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.CharacterMaximumLength == (property.DataSourcePrecisionLength ?? 1);
                    case CoreType.DateTimeNullable: return ((sqlColumn.DataType == "datetime" && property.DatePart == StoreDatePart.DateTime && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6)) || (sqlColumn.DataType == "date" && property.DatePart == StoreDatePart.Date)) && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.DateTimeOffsetNullable: return sqlColumn.DataType == "datetime" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6);
                    case CoreType.TimeSpanNullable: return sqlColumn.DataType == "time" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6);
                    case CoreType.DateOnlyNullable: return sqlColumn.DataType == "date" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.TimeOnlyNullable: return sqlColumn.DataType == "time" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.DatetimePrecision == (property.DataSourcePrecisionLength ?? 6);
                    case CoreType.GuidNullable: return sqlColumn.DataType == "binary" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;

                    case CoreType.String:
                        //decided by the length the model asks for, the existing column only has a length when it is already varchar
                        if (property.DataSourcePrecisionLength.HasValue)
                            return sqlColumn.DataType == "varchar" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.CharacterMaximumLength == property.DataSourcePrecisionLength.Value;
                        else
                            return sqlColumn.DataType == "text" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                }
            }

            if (property.Type == typeof(byte[]))
            {
                if (property.DataSourcePrecisionLength.HasValue)
                    return sqlColumn.DataType == "varbinary" && sqlColumn.IsNullable == !property.IsDataSourceNotNull && sqlColumn.CharacterMaximumLength == property.DataSourcePrecisionLength.Value;
                else
                    return sqlColumn.DataType == "blob" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
            }

            throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} cannot match type {property.Type.Name} to an {nameof(MySqlEngine)} type.");
        }
        private SqlColumnType[] GetSqlColumns(ModelDetail model)
        {
            var query = $@"SELECT C.TABLE_NAME, C.COLUMN_NAME, DATA_TYPE, IS_NULLABLE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, DATETIME_PRECISION
	,C.EXTRA LIKE '%auto_increment%' OR C.COLUMN_DEFAULT = 'uuid_to_bin(uuid(),true)' AS IS_AUTOGENERATED
	,RC.CONSTRAINT_TYPE = 'PRIMARY KEY' AS IS_PRIMARYKEY
FROM INFORMATION_SCHEMA.COLUMNS C
LEFT OUTER JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE KF ON KF.COLUMN_NAME = C.COLUMN_NAME AND C.TABLE_NAME = KF.TABLE_NAME AND C.TABLE_SCHEMA = KF.TABLE_SCHEMA
LEFT OUTER JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS RC ON RC.CONSTRAINT_NAME = KF.CONSTRAINT_NAME AND RC.TABLE_NAME = KF.TABLE_NAME AND RC.TABLE_SCHEMA = KF.TABLE_SCHEMA
WHERE C.TABLE_SCHEMA = DATABASE() AND LOWER(C.TABLE_NAME) = '{model.DataSourceEntityName.ToLower()}'";

            var sqlColumns = ExecuteSqlQuery(query).Select(x => (IList<object>)x).Select(x => new SqlColumnType()
            {
                Table = (string)x[0],
                Column = (string)x[1],
                DataType = (string)x[2],
                IsNullable = (string)x[3] == "YES",
                CharacterMaximumLength = x[4] != DBNull.Value ? (long)x[4] : (long?)null,
                NumericPrecision = x[5] != DBNull.Value ? (uint)x[5] : (uint?)null,
                NumericScale = x[6] != DBNull.Value ? (uint)x[6] : (uint?)null,
                DatetimePrecision = x[7] != DBNull.Value ? (uint)x[7] : (uint?)null,
                IsAutoGenerated = x[8] != DBNull.Value && Convert.ToInt64(x[8]) == 1, //9.x returns long, 8.0 returns ulong
                IsPrimaryKey = x[9] != DBNull.Value && Convert.ToInt64(x[9]) == 1, //9.x returns long, 8.0 returns ulong
            }).ToArray();

            return sqlColumns;
        }
        private SqlConstraint[] GetSqlConstraints(ModelDetail model)
        {
            var query = $@"SELECT RC.CONSTRAINT_NAME FK_Name, KF.TABLE_SCHEMA FK_Schema, KF.TABLE_NAME FK_Table, KF.COLUMN_NAME FK_Column, RC.UNIQUE_CONSTRAINT_NAME PK_Name, KF.REFERENCED_TABLE_SCHEMA PK_Schema, KF.REFERENCED_TABLE_NAME PK_Table, KF.REFERENCED_COLUMN_NAME PK_Column
FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS RC
LEFT JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE KF ON RC.CONSTRAINT_NAME = KF.CONSTRAINT_NAME AND RC.CONSTRAINT_SCHEMA = KF.CONSTRAINT_SCHEMA
LEFT JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS TCKF ON KF.CONSTRAINT_NAME = TCKF.CONSTRAINT_NAME AND KF.CONSTRAINT_SCHEMA = TCKF.CONSTRAINT_SCHEMA
WHERE TCKF.CONSTRAINT_TYPE = 'FOREIGN KEY'
AND KF.TABLE_SCHEMA = DATABASE() AND LOWER(KF.TABLE_NAME) = '{model.DataSourceEntityName.ToLower()}'
ORDER BY RC.CONSTRAINT_NAME, KF.ORDINAL_POSITION";

            var sqlConstrains = ExecuteSqlQuery(query).Select(x => (IList<object>)x).Select(x => new SqlConstraint()
            {
                FK_Name = (string)x[0],
                FK_Schema = (string)x[1],
                FK_Table = (string)x[2],
                FK_Column = (string)x[3],
                PK_Name = (string)x[4],
                PK_Schema = (string)x[5],
                PK_Table = (string)x[6],
                PK_Column = (string)x[7],
            }).ToArray();

            return sqlConstrains;
        }
        private SqlIndex[] GetSqlIndexes(ModelDetail model)
        {
            var query = $@"SELECT INDEX_NAME, NON_UNIQUE, COLUMN_NAME, COLLATION
FROM INFORMATION_SCHEMA.STATISTICS
WHERE TABLE_SCHEMA = DATABASE() AND LOWER(TABLE_NAME) = '{model.DataSourceEntityName.ToLower()}' AND INDEX_NAME <> 'PRIMARY'
ORDER BY INDEX_NAME, SEQ_IN_INDEX";

            var sqlIndexes = new List<SqlIndex>();
            SqlIndex? sqlIndex = null;
            foreach (var x in ExecuteSqlQuery(query).Select(x => (IList<object>)x))
            {
                var name = (string)x[0];
                if (sqlIndex is null || sqlIndex.Name != name)
                {
                    sqlIndex = new SqlIndex()
                    {
                        Name = name,
                        Columns = new(),
                        Descending = new(),
                        IsUnique = Convert.ToInt64(x[1]) == 0,
                    };
                    sqlIndexes.Add(sqlIndex);
                }
                sqlIndex.Columns.Add(x[2] != DBNull.Value ? (string)x[2] : String.Empty);
                sqlIndex.Descending.Add(x[3] != DBNull.Value && (string)x[3] == "D");
            }

            return sqlIndexes.ToArray();
        }
