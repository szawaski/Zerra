        //the connection of an operation, which is the transaction's when there is one and closes with the operation when not
        private readonly struct EngineConnection : IDisposable
        {
            private readonly MySqlConnection connection;
            private readonly MySqlTransaction? transaction;
            private readonly RepoTransactionPart? part;
            public EngineConnection(MySqlConnection connection, MySqlTransaction? transaction, RepoTransactionPart? part)
            {
                this.connection = connection;
                this.transaction = transaction;
                this.part = part;
            }
            public MySqlCommand CreateCommand()
            {
                var command = connection.CreateCommand();
                command.Transaction = transaction;
                return command;
            }
            public MySqlCommand CreateCommand(MySqlTransaction? local)
            {
                var command = connection.CreateCommand();
                command.Transaction = local ?? transaction;
                return command;
            }
            public MySqlTransaction? BeginWhenNone() => transaction is null ? connection.BeginTransaction() : null;
            public async ValueTask<MySqlTransaction?> BeginWhenNoneAsync(CancellationToken cancellationToken) => transaction is null ? await connection.BeginTransactionAsync(cancellationToken) : null;
            public void Dispose()
            {
                if (part is null)
                    connection.Dispose();
                else
                    part.Exit();
            }
        }
        private EngineConnection OpenConnection()
        {
            var transaction = RepoTransaction.Current;
            if (transaction is not null)
            {
                var part = transaction.Enter(connectionString, nameof(MySqlEngine), BeginTransactionPart);
                return new EngineConnection((MySqlConnection)part.Connection, (MySqlTransaction)part.Transaction, part);
            }
            var connection = new MySqlConnection(connectionString);
            try
            {
                connection.Open();
            }
            catch
            {
                connection.Dispose();
                throw;
            }
            return new EngineConnection(connection, null, null);
        }
        private async ValueTask<EngineConnection> OpenConnectionAsync(CancellationToken cancellationToken)
        {
            var transaction = RepoTransaction.Current;
            if (transaction is not null)
            {
                var part = await transaction.EnterAsync(connectionString, nameof(MySqlEngine), BeginTransactionPartAsync, cancellationToken);
                return new EngineConnection((MySqlConnection)part.Connection, (MySqlTransaction)part.Transaction, part);
            }
            var connection = new MySqlConnection(connectionString);
            try
            {
                await connection.OpenAsync(cancellationToken);
            }
            catch
            {
                connection.Dispose();
                throw;
            }
            return new EngineConnection(connection, null, null);
        }
        private DbRepoTransactionPart BeginTransactionPart(IsolationLevel isolationLevel)
        {
            var connection = new MySqlConnection(connectionString);
            try
            {
                connection.Open();
                return new DbRepoTransactionPart(connection, connection.BeginTransaction(isolationLevel));
            }
            catch
            {
                connection.Dispose();
                throw;
            }
        }
        private async Task<DbRepoTransactionPart> BeginTransactionPartAsync(IsolationLevel isolationLevel, CancellationToken cancellationToken)
        {
            var connection = new MySqlConnection(connectionString);
            try
            {
                await connection.OpenAsync(cancellationToken);
                return new DbRepoTransactionPart(connection, await connection.BeginTransactionAsync(isolationLevel, cancellationToken));
            }
            catch
            {
                connection.Dispose();
                throw;
            }
        }

        /// <inheritdoc />
        public object? ExecuteLinq<TModel, TResult>(LinqQuery query, ModelDetail modelDetail) where TModel : class, new()
        {
            var statement = LinqMySqlConverter.ConvertLinq(query, modelDetail);

            using (var connection = OpenConnection())
            {
                if (JoinsText(statement))
                    SetJoinLimit(connection);
                switch (query.Terminal)
                {
                    case LinqTerminal.Any:
                        using (var command = connection.CreateCommand())
                        {
                            command.CommandTimeout = 0;
                            command.CommandText = statement.Sql;
                            using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                                return reader.HasRows;
                        }
                    case LinqTerminal.Count:
                    case LinqTerminal.LongCount:
                    case LinqTerminal.Sum:
                    case LinqTerminal.Min:
                    case LinqTerminal.Max:
                    case LinqTerminal.Average:
                        using (var command = connection.CreateCommand())
                        {
                            command.CommandTimeout = 0;
                            command.CommandText = statement.Sql;
                            var value = command.ExecuteScalar();
                            if (value is null || value is DBNull)
                                return null;
                            return ConvertLinqValue(value, typeof(TResult));
                        }
                    default:
                        {
                            var pieces = ReadLinqPieces(connection, statement);
                            var results = query.Take is int take && take <= 1024 ? new List<TResult>(take) : new List<TResult>();
                            using (var command = connection.CreateCommand())
                            {
                                command.CommandTimeout = 0;
                                command.CommandText = statement.Sql;
                                using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                                {
                                    var shape = statement.Plan.Shape!;
                                    while (reader.Read())
                                        results.Add((TResult)ReadLinqElement(reader, shape, pieces)!);
                                }
                            }
                            return results;
                        }
                }
            }
        }
        //the rows of each relation for all the parents at once, matched to them by the key, read before the parents so each element is built whole from its row
        private static LinqPieceElements[]? ReadLinqPieces(EngineConnection connection, LinqStatement statement)
        {
            if (statement.Pieces is null)
                return null;
            var pieces = new LinqPieceElements[statement.Pieces.Length];
            for (var p = 0; p < pieces.Length; p++)
            {
                var piece = statement.Pieces[p];
                var piecePieces = ReadLinqPieces(connection, piece);
                var elements = statement.Plan.Pieces[p].NewElements();
                pieces[p] = elements;
                using (var command = connection.CreateCommand())
                {
                    command.CommandTimeout = 0;
                    command.CommandText = piece.Sql;
                    using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                    {
                        var shape = piece.Plan.Shape!;
                        var keyColumn = piece.Plan.ParentKeyColumn!.Value;
                        var keyColumns = statement.Plan.Pieces[p].CompositeKey ? piece.Plan.ParentKeyColumns : null;
                        var keyType = statement.Plan.Pieces[p].RelatedKey.Type;
                        while (reader.Read())
                        {
                            var element = ReadLinqElement(reader, shape, piecePieces);
                            if (keyColumns is null)
                                AddLinqPiece(reader, keyColumn, elements, element, keyType);
                            else if (LinqKey.Read(reader, keyColumns) is { } key)
                                elements.Add(key, element);
                        }
                    }
                }
            }
            return pieces;
        }
        //a key read as its own type where the column holds it, so it isn't boxed for every row, a Guid from the 16 bytes of a binary column
        private static void AddLinqPiece(DbDataReader reader, int column, LinqPieceElements elements, object? element, Type keyType)
        {
            if (reader.IsDBNull(column))
                return;
            var type = reader.GetFieldType(column);
            switch (elements)
            {
                case LinqPieceElements<Guid> guids when type == typeof(Guid): guids.Add(reader.GetGuid(column), element); return;
                case LinqPieceElements<Guid> guids when type == typeof(byte[]): guids.Add(ReadGuid(reader, column), element); return;
                case LinqPieceElements<int> ints when type == typeof(int): ints.Add(reader.GetInt32(column), element); return;
                case LinqPieceElements<long> longs when type == typeof(long): longs.Add(reader.GetInt64(column), element); return;
                case LinqPieceElements<string> texts when type == typeof(string): texts.Add(reader.GetString(column), element); return;
                default: elements.Add(ConvertLinqValue(reader.GetValue(column), keyType), element); return;
            }
        }
        private static List<object?>? FindLinqPiece(DbDataReader reader, int column, LinqPieceElements elements, Type keyType)
        {
            if (reader.IsDBNull(column))
                return null;
            var type = reader.GetFieldType(column);
            switch (elements)
            {
                case LinqPieceElements<Guid> guids when type == typeof(Guid): return guids.Find(reader.GetGuid(column));
                case LinqPieceElements<Guid> guids when type == typeof(byte[]): return guids.Find(ReadGuid(reader, column));
                case LinqPieceElements<int> ints when type == typeof(int): return ints.Find(reader.GetInt32(column));
                case LinqPieceElements<long> longs when type == typeof(long): return longs.Find(reader.GetInt64(column));
                case LinqPieceElements<string> texts when type == typeof(string): return texts.Find(reader.GetString(column));
                default: return elements.Find(ConvertLinqValue(reader.GetValue(column), keyType));
            }
        }
        [ThreadStatic]
        private static byte[]? guidBytes;
        private static Guid ReadGuid(DbDataReader reader, int column)
        {
            var bytes = guidBytes ??= new byte[16];
            _ = reader.GetBytes(column, 0, bytes, 0, 16);
            return new Guid(bytes, true);
        }
        private static object? ReadLinqElement(DbDataReader reader, LinqShape shape, LinqPieceElements[]? pieces)
        {
            switch (shape.Kind)
            {
                case LinqShapeKind.Column:
                    return ReadLinqValue(reader, shape.Column!.Index, shape.Type);
                case LinqShapeKind.Model:
                    {
                        if (shape.JoinedKey is not null && reader.IsDBNull(shape.JoinedKey.Index))
                            return null;
                        var model = shape.Model!.Creator();
                        var members = shape.ModelMembers!;
                        var columns = shape.ModelColumns!;
                        for (var i = 0; i < members.Length; i++)
                        {
                            var member = members[i];
                            if (member.CoreType.HasValue)
                            {
                                ReadLinqMember(reader, columns[i].Index, member.CoreType.Value, member.Setter, model);
                            }
                            else
                            {
                                var value = ReadLinqValue(reader, columns[i].Index, member.Type);
                                if (value is not null)
                                    member.SetterBoxed(model, value);
                            }
                        }
                        if (shape.ModelRelations is not null)
                        {
                            foreach (var relation in shape.ModelRelations)
                            {
                                var value = ReadLinqElement(reader, relation, pieces);
                                if (value is not null)
                                    relation.RelationMember!.SetterBoxed(model, value);
                            }
                        }
                        return model;
                    }
                case LinqShapeKind.Object:
                    {
                        object instance;
                        if (shape.Arguments is null || shape.Arguments.Length == 0)
                        {
                            instance = shape.Constructor is null ? TypeAnalyzer.GetTypeDetail(shape.Type).CreatorBoxed!() : shape.Constructor.Invoke(Array.Empty<object>());
                        }
                        else
                        {
                            var arguments = shape.ArgumentValues();
                            for (var i = 0; i < arguments.Length; i++)
                                arguments[i] = ReadLinqElement(reader, shape.Arguments[i], pieces);
                            instance = shape.Constructor!.Invoke(arguments);
                        }
                        if (shape.Members is not null)
                        {
                            for (var i = 0; i < shape.Members.Length; i++)
                            {
                                var member = shape.Members[i];
                                var value = shape.Values![i];
                                //a member set from a column of the model's type reads it typed, as the model's own members do
                                if (value.Kind == LinqShapeKind.Column && value.Column!.Member is { CoreType: not null } column && column.Type == member.Type)
                                {
                                    ReadLinqMember(reader, value.Column.Index, column.CoreType.Value, member.Setter!, instance);
                                    continue;
                                }
                                var element = ReadLinqElement(reader, value, pieces);
                                if (element is not null)
                                    member.SetterBoxed!(instance, element);
                            }
                        }
                        return instance;
                    }
                default:
                    return shape.BuildRelation(shape.Piece!.CompositeKey ? (LinqKey.Read(reader, shape.Piece.ParentColumns) is { } key ? pieces![shape.PieceIndex].Find(key) : null) : FindLinqPiece(reader, shape.Piece!.ParentColumn, pieces![shape.PieceIndex], shape.Piece.ParentKey.Type));
            }
        }
        private static object? ReadLinqValue(DbDataReader reader, int i, Type type)
        {
            if (reader.IsDBNull(i))
                return null;
            return ConvertLinqValue(reader.GetValue(i), type);
        }
        //a joined text is cut at this session limit, which is only 1024 characters on MySQL
        private const string joinLimitSql = "SET SESSION group_concat_max_len=4294967295";
        private static bool JoinsText(LinqStatement statement)
        {
            if (statement.Sql.Contains("GROUP_CONCAT(", StringComparison.Ordinal))
                return true;
            if (statement.Pieces is not null)
            {
                foreach (var piece in statement.Pieces)
                {
                    if (JoinsText(piece))
                        return true;
                }
            }
            return false;
        }
