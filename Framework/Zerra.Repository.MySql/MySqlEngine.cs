        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlInsert<TModel>(TModel model, Graph? graph, ModelDetail modelDetail, bool getIdentities) where TModel : class, new()
        {
            var sbColumns = new CharWriter();
            var sbValues = new CharWriter();
            try
            {
                GenerateSqlInsertRow(model, graph, modelDetail, ref sbColumns, ref sbValues);

                string sql;
                if (getIdentities)
                {
                    //MySQL has no RETURNING, LAST_INSERT_ID() only gives AUTO_INCREMENT values, the same reason the schema generation rejects these
                    if (modelDetail.IdentityAutoGeneratedMembers.Any(x => x.CoreType == CoreType.Guid))
                        throw new NotSupportedException("MySQL does not support auto generated GUIDs as identities.");

                    if (sbColumns.Length > 0 && sbValues.Length > 0)
                        sql = $"INSERT INTO `{modelDetail.DataSourceEntityName}` ({sbColumns.ToString()}) VALUES ({sbValues.ToString()});SELECT LAST_INSERT_ID();";
                    else
                        sql = $"INSERT INTO `{modelDetail.DataSourceEntityName}` DEFAULT VALUES;SELECT LAST_INSERT_ID();";
                }
                else
                {
                    if (sbColumns.Length > 0 && sbValues.Length > 0)
                        sql = $"INSERT INTO `{modelDetail.DataSourceEntityName}` ({sbColumns.ToString()}) VALUES ({sbValues.ToString()})";
                    else
                        sql = $"INSERT INTO `{modelDetail.DataSourceEntityName}` DEFAULT VALUES";
                }
                return sql;
            }
            finally
            {
                sbColumns.Dispose();
                sbValues.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static void GenerateSqlInsertRow<TModel>(TModel model, Graph? graph, ModelDetail modelDetail, ref CharWriter sbColumns, ref CharWriter sbValues) where TModel : class, new()
        {
            foreach (var modelPropertyDetail in modelDetail.NonAutoGeneratedNonRelationMembers)
            {
                var isProperty = graph is null || graph.HasMember(modelPropertyDetail.Name);
                if (!modelPropertyDetail.IsNullable || isProperty)
                {
                    object? value;
                    if (isProperty)
                        value = modelPropertyDetail.GetterBoxed(model);
                    else
                        value = modelPropertyDetail.CreatorBoxed();

                    if (value is not null)
                    {
                        var property = modelPropertyDetail.StoreName;

                        if (sbColumns.Length > 0)
                            sbColumns.Write(',');
                        sbColumns.Write('`');
                        sbColumns.Write(property);
                        sbColumns.Write('`');

                        if (sbValues.Length > 0)
                            sbValues.Write(',');
                        AppendSqlValue(ref sbValues, modelPropertyDetail, value, false, false);
                    }
                }
            }
        }
        //consecutive models writing the same columns share a statement
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlInsertMany<TModel>(object[] models, ref int index, Graph? graph, ModelDetail modelDetail) where TModel : class, new()
        {
            var sb = new CharWriter();
            var sbColumns = new CharWriter();
            var sbValues = new CharWriter();
            var sbRowColumns = new CharWriter();
            try
            {
                GenerateSqlInsertRow((TModel)models[index], graph, modelDetail, ref sbColumns, ref sbValues);
                index++;
                if (sbColumns.Length == 0)
                    return $"INSERT INTO `{modelDetail.DataSourceEntityName}` DEFAULT VALUES";

                sb.Write("INSERT INTO `");
                sb.Write(modelDetail.DataSourceEntityName);
                sb.Write("` (");
                sb.Write(sbColumns);
                sb.Write(") VALUES (");
                sb.Write(sbValues);
                sb.Write(')');

                var rows = 1;
                while (index < models.Length && rows < batchRows)
                {
                    sbRowColumns.Clear();
                    sbValues.Clear();
                    GenerateSqlInsertRow((TModel)models[index], graph, modelDetail, ref sbRowColumns, ref sbValues);
                    if (!sbRowColumns.ToSpan().SequenceEqual(sbColumns.ToSpan()))
                        break;
                    sb.Write(",(");
                    sb.Write(sbValues);
                    sb.Write(')');
                    rows++;
                    index++;
                }
                return sb.ToString();
            }
            finally
            {
                sbRowColumns.Dispose();
                sbValues.Dispose();
                sbColumns.Dispose();
                sb.Dispose();
            }
        }
        //each insert returning its identities is its own statement, the results come back in the order of the statements where the rows of one statement aren't promised in order
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlInsertManyGetIdentities<TModel>(object[] models, ref int index, Graph? graph, ModelDetail modelDetail) where TModel : class, new()
        {
            var sb = new CharWriter();
            try
            {
                var statements = 0;
                do
                {
                    var sql = GenerateSqlInsert((TModel)models[index], graph, modelDetail, true);
                    sb.Write(sql);
                    if (sql[sql.Length - 1] != ';')
                        sb.Write(';');
                    sb.Write("\r\n");
                    index++;
                    statements++;
                }
                while (index < models.Length && statements < batchRows);
                return sb.ToString();
            }
            finally
            {
                sb.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlUpdateMany<TModel>(object[] models, ref int index, Graph? graph, ModelDetail modelDetail) where TModel : class, new()
        {
            var sb = new CharWriter();
            try
            {
                var statements = 0;
                do
                {
                    var sql = GenerateSqlUpdate((TModel)models[index], graph, modelDetail);
                    index++;
                    statements++;
                    if (sql is null)
                        continue;
                    sb.Write(sql);
                    sb.Write(";\r\n");
                }
                while (index < models.Length && statements < batchRows);
                return sb.ToString();
            }
            finally
            {
                sb.Dispose();
            }
        }
        //the rows of one statement and the statements of one command
        private const int batchRows = 1000;
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string? GenerateSqlUpdate<TModel>(TModel model, Graph? graph, ModelDetail modelDetail) where TModel : class, new()
        {
            if (modelDetail.IdentityMembers.Count == 0)
                return null;

            var writer = new CharWriter();
            try
            {
                writer.Write("UPDATE `");
                writer.Write(modelDetail.DataSourceEntityName);
                writer.Write("` SET ");
                var first = true;
                foreach (var modelPropertyInfo in modelDetail.NonAutoGeneratedNonRelationMembers)
                {
                    if (graph is null || graph.HasMember(modelPropertyInfo.Name))
                    {
                        var value = modelPropertyInfo.GetterBoxed(model);
                        var property = modelPropertyInfo.StoreName;

                        if (first)
                            first = false;
                        else
                            writer.Write(',');
                        writer.Write('`');
                        writer.Write(property);
                        writer.Write('`');
                        AppendSqlValue(ref writer, modelPropertyInfo, value, true, false);
                    }
                }

                if (writer.Length == 0)
                    return null;

                writer.Write(" WHERE ");

                first = true;
                foreach (var modelPropertyInfo in modelDetail.IdentityMembers)
                {
                    var value = modelPropertyInfo.GetterBoxed(model);
                    var property = modelPropertyInfo.StoreName;

                    if (first)
                        first = false;
                    else
                        writer.Write(" AND ");
                    writer.Write('`');
                    writer.Write(property);
                    writer.Write('`');
                    AppendSqlValue(ref writer, modelPropertyInfo, value, false, true);
                }

                return writer.ToString();
            }
            finally
            {
                writer.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlDelete(ICollection ids, ModelDetail modelDetail)
        {
            var sbWhere = new CharWriter();
            try
            {
                sbWhere.Write($"DELETE FROM `");
                sbWhere.Write(modelDetail.DataSourceEntityName);
                sbWhere.Write("` WHERE ");

                if (modelDetail.IdentityMembers.Count == 1)
                {
                    var modelPropertyInfo = modelDetail.IdentityMembers[0];
                    sbWhere.Write('`');
                    sbWhere.Write(modelPropertyInfo.StoreName);
                    sbWhere.Write("` IN (");

                    var first = true;
                    foreach (var id in ids)
                    {
                        if (first)
                            first = false;
                        else
                            sbWhere.Write(',');
                        AppendSqlValue(ref sbWhere, modelPropertyInfo, id, false, false);
                    }

                    sbWhere.Write(')');
                }
                else
                {
                    var first = true;
                    foreach (var id in ids)
                    {
                        if (first)
                            first = false;
                        else
                            sbWhere.Write(" OR ");
                        sbWhere.Write('(');

                        var idArray = ((ICollection)id).Cast<object>().ToArray();

                        var i = 0;
                        foreach (var modelPropertyInfo in modelDetail.IdentityMembers)
                        {
                            var value = idArray[i];

                            if (i > 0)
                                sbWhere.Write(" AND ");
                            sbWhere.Write('`');
                            sbWhere.Write(modelPropertyInfo.StoreName);
                            sbWhere.Write('`');
                            AppendSqlValue(ref sbWhere, modelPropertyInfo, value, false, true);
                            i++;
                        }
                        sbWhere.Write(')');
                    }
                }

                return sbWhere.ToString();
            }
            finally
            {
                sbWhere.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string? GenerateSqlUpdateWhere<TModel>(TModel model, Graph graph, ModelDetail modelDetail, string sqlWhere) where TModel : class, new()
        {
            var writer = new CharWriter();
            try
            {
                writer.Write("UPDATE `");
                writer.Write(modelDetail.DataSourceEntityName);
                writer.Write("` SET ");
                var first = true;
                foreach (var modelPropertyInfo in modelDetail.NonAutoGeneratedNonRelationMembers)
                {
                    if (!graph.HasMember(modelPropertyInfo.Name))
                        continue;
                    var value = modelPropertyInfo.GetterBoxed(model);

                    if (first)
                        first = false;
                    else
                        writer.Write(',');
                    writer.Write('`');
                    writer.Write(modelPropertyInfo.StoreName);
                    writer.Write('`');
                    AppendSqlValue(ref writer, modelPropertyInfo, value, true, false);
                }

                if (first)
                    return null;

                writer.Write(sqlWhere);
                return writer.ToString();
            }
            finally
            {
                writer.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static void AppendSqlValue(ref CharWriter writer, ModelMemberDetail modelPropertyDetail, object? value, bool assigningValue, bool comparingValue)
        {
            if (value is null)
            {
                if (assigningValue)
                    writer.Write("=NULL");
                else if (comparingValue)
                    writer.Write("IS NULL");
                else
                    writer.Write("NULL");
                return;
            }

            if (modelPropertyDetail.EnumType is not null)
            {
                if (assigningValue || comparingValue)
                    writer.Write('=');
                writer.Write('\'');
                writer.Write(EnumName.GetName(modelPropertyDetail.EnumType, value).Replace("\\", "\\\\").Replace("'", "''"));
                writer.Write('\'');
                return;
            }

            if (modelPropertyDetail.CoreType.HasValue)
            {
                if (assigningValue || comparingValue)
                    writer.Write('=');
                switch (modelPropertyDetail.CoreType.Value)
                {
                    case CoreType.String:
                        writer.Write('\'');
                        writer.Write(((string)value).Replace("\\", "\\\\").Replace("'", "''"));
                        writer.Write('\'');
                        return;

                    case CoreType.Boolean:
                    case CoreType.BooleanNullable:
                        writer.Write((bool)value == false ? '0' : '1');
                        return;
                    case CoreType.Byte:
                    case CoreType.ByteNullable:
                        writer.Write((byte)value);
                        return;
                    case CoreType.Int16:
                    case CoreType.Int16Nullable:
                        writer.Write((short)value);
                        return;
                    case CoreType.Int32:
                    case CoreType.Int32Nullable:
                        writer.Write((int)value);
                        return;
                    case CoreType.Int64:
                    case CoreType.Int64Nullable:
                        writer.Write((long)value);
                        return;
                    case CoreType.Single:
                    case CoreType.SingleNullable:
                        writer.Write((float)value);
                        return;
                    case CoreType.Double:
                    case CoreType.DoubleNullable:
                        writer.Write((double)value);
                        return;
                    case CoreType.Decimal:
                    case CoreType.DecimalNullable:
                        writer.Write((decimal)value);
                        return;
                    case CoreType.Char:
                    case CoreType.CharNullable:
                        writer.Write('\'');
                        var castedChar = (char)value;
                        if (castedChar == '\'')
                            writer.Write("''");
                        else if (castedChar == '\\')
                            writer.Write("\\\\");
                        else
                            writer.Write(castedChar);
                        writer.Write('\'');
                        return;
                    case CoreType.DateTime:
                    case CoreType.DateTimeNullable:
                        writer.Write('\'');
                        writer.Write((DateTime)value, CharWriter.DateTimeFormat.MySql);
                        writer.Write('\'');
                        return;
                    case CoreType.DateTimeOffset:
                    case CoreType.DateTimeOffsetNullable:
                        writer.Write('\'');
                        writer.Write((DateTimeOffset)value, CharWriter.DateTimeFormat.MySql);
                        writer.Write('\'');
                        return;
                    case CoreType.TimeSpan:
                    case CoreType.TimeSpanNullable:
                        writer.Write('\'');
                        writer.Write((TimeSpan)value, CharWriter.TimeFormat.MySql);
                        writer.Write('\'');
                        return;
                    case CoreType.DateOnly:
                    case CoreType.DateOnlyNullable:
                        writer.Write('\'');
                        writer.Write((DateOnly)value, CharWriter.DateTimeFormat.MySql);
                        writer.Write('\'');
                        return;
                    case CoreType.TimeOnly:
                    case CoreType.TimeOnlyNullable:
                        writer.Write('\'');
                        writer.Write((TimeOnly)value, CharWriter.TimeFormat.MySql);
                        writer.Write('\'');
                        return;
                    case CoreType.Guid:
                    case CoreType.GuidNullable:
                        writer.Write("0x");
                        writer.Write(((Guid)value).ToByteArray(true), CharWriter.ByteFormat.Hex);
                        return;

                    default:
                        throw new NotImplementedException();
                }
            }

            if (modelPropertyDetail.Type == typeof(byte[]))
            {
                if (assigningValue || comparingValue)
                    writer.Write('=');
                writer.Write("0x");
                writer.Write((byte[])value, CharWriter.ByteFormat.Hex);
                return;
            }

            throw new Exception($"Cannot convert type to SQL value {modelPropertyDetail.Type.Name}");
        }

