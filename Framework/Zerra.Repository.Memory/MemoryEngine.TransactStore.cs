        //a table of a type is first made in generic code, which keeps what a transaction needs to copy it later when only its type is known
        private object NewTable<TModel>() where TModel : class, new()
        {
            _ = tableCopiers.TryAdd(typeof(TModel), CopyTable<TModel>);
            return new ConcurrentList<TModel>();
        }
        private static object CopyTable<TModel>(object table) where TModel : class, new()
        {
            var modelDetail = ModelAnalyzer.GetModel(typeof(TModel));
            var copy = new ConcurrentList<TModel>();
            foreach (var row in (ConcurrentList<TModel>)table)
                copy.Add(CopyRow(row, modelDetail));
            return copy;
        }
        private static TModel CopyRow<TModel>(TModel row, ModelDetail modelDetail) where TModel : class, new()
        {
            var copy = new TModel();
            foreach (var member in modelDetail.Members)
            {
                if (member.IsDataSourceEntity || member.IsRelated)
                    continue;
                member.SetterBoxed(copy, member.GetterBoxed(row));
            }
            return copy;
        }
        private void RecordInsert<TModel>(MemoryTransactionPart part, TModel row, ModelDetail modelDetail) where TModel : class, new()
        {
            var saved = CopyRow(row, modelDetail);
            var source = (ConcurrentList<TModel>)data.GetOrAdd(typeof(TModel), NewTable<TModel>);
            if (modelDetail.IdentityAutoGeneratedMembers.Count > 0)
            {
                //another writer can be given the same identity while this one waits to commit
                var identity = ModelAnalyzer.GetIdentity(typeof(TModel), saved);
                part.RecordCheck(() =>
                {
                    if (source.Any(x => ModelAnalyzer.CompareIdentities(identity, ModelAnalyzer.GetIdentity(typeof(TModel), x))))
                        throw new InvalidOperationException($"{typeof(TModel).Name} was given the same identity by another writer");
                });
            }
            part.Record(() =>
            {
                source.Add(saved);
                MapRelated(data, saved, modelDetail, false);
            });
        }

        //everything is copied the first time a transaction uses this store: a row can be related to any other and the transaction must not touch the rows others read
        private MemoryTransactionPart BeginTransactionPart(IsolationLevel isolationLevel)
        {
            var store = new ConcurrentFactoryDictionary<Type, object>();
            lock (commitLock)
            {
                foreach (var pair in data)
                    _ = store.TryAdd(pair.Key, tableCopiers[pair.Key](pair.Value));
            }
            foreach (var pair in store)
            {
                var modelDetail = ModelAnalyzer.GetModel(pair.Key);
                foreach (var row in (IList)pair.Value)
                {
                    foreach (var member in modelDetail.Members)
                    {
                        if (member.IsRelated)
                            LinkRelated(store, row, modelDetail, member);
                    }
                }
            }
            return new MemoryTransactionPart(store, commitLock);
        }

        private sealed class MemoryTransactionPart : RepoTransactionPart
        {
            private readonly object commitLock;
            private readonly List<Action> checks = new();
            private readonly List<Action> writes = new();
            public ConcurrentFactoryDictionary<Type, object> Store { get; }
            public override bool CommitsLast => true;
            public MemoryTransactionPart(ConcurrentFactoryDictionary<Type, object> store, object commitLock)
            {
                this.Store = store;
                this.commitLock = commitLock;
            }
            public void RecordCheck(Action check)
            {
                lock (checks)
                    checks.Add(check);
            }
            public void Record(Action write)
            {
                lock (writes)
                    writes.Add(write);
            }
            public override void Commit()
            {
                lock (commitLock)
                {
                    foreach (var check in checks)
                        check();
                    foreach (var write in writes)
                        write();
                }
            }
            public override Task CommitAsync(CancellationToken cancellationToken)
            {
                cancellationToken.ThrowIfCancellationRequested();
                Commit();
                return Task.CompletedTask;
            }
            public override void Rollback() { }
            public override Task RollbackAsync() => Task.CompletedTask;
            public override void Close() { }
        }

        private static Graph GetAllLocalMemberGraph(Type type)
        {
            return allLocalMemberGraph.GetOrAdd(type, (type) =>
            {
                var modelType = ModelAnalyzer.GetModel(type);
                var graph = new Graph();
                foreach (var member in modelType.Members)
                {
                    if (member.IsDataSourceEntity || member.IsRelated)
                        continue;
                    graph.AddMember(member.Name);
                }
                return graph;
            });
        }
        private static Graph BuildLocalGraph(Type type, Graph? inputGraph)
        {
            if (inputGraph == null)
                return GetAllLocalMemberGraph(type);

            var modelType = ModelAnalyzer.GetModel(type);
            var graph = new Graph();
            foreach (var member in modelType.Members)
            {
                if (member.IsDataSourceEntity || member.IsRelated)
                    continue;
                if (!inputGraph.HasMember(member.Name))
                    continue;
                graph.AddMember(member.Name);
            }
            return graph;
        }

        private static object GenerateIdentity<TModel>(ConcurrentList<TModel> source, ModelMemberDetail property) where TModel : class, new()
        {
            if (!property.CoreType.HasValue)
                throw new InvalidOperationException($"Identity property {property.Name} does not have a core type.");
            if (property.CoreType.Value == CoreType.Guid)
                return Guid.NewGuid();

            var last = source.LastOrDefault();
            return property.CoreType.Value switch
            {
                CoreType.Byte => last == null ? (byte)1 : (byte)((byte)property.GetterBoxed(last)! + 1),
                CoreType.SByte => last == null ? (sbyte)1 : (sbyte)((sbyte)property.GetterBoxed(last)! + 1),
                CoreType.Int16 => last == null ? (short)1 : (short)((short)property.GetterBoxed(last)! + 1),
                CoreType.UInt16 => last == null ? (ushort)1 : (ushort)((ushort)property.GetterBoxed(last)! + 1),
                CoreType.Int32 => last == null ? 1 : (int)property.GetterBoxed(last)! + 1,
                CoreType.UInt32 => last == null ? (uint)1 : (uint)((uint)property.GetterBoxed(last)! + 1),
                CoreType.Int64 => (object)(last == null ? 1L : (long)property.GetterBoxed(last)! + 1L),
                CoreType.UInt64 => (object)(last == null ? 1UL : (ulong)((ulong)property.GetterBoxed(last)! + 1UL)),
                _ => throw new InvalidOperationException($"Identity property {property.Name} has unsupported core type {property.CoreType.Value}."),
            };
        }

        private static void MapRelated(ConcurrentFactoryDictionary<Type, object> store, object model, ModelDetail modelDetail, bool isDelete)
        {
            MapRelated(store, model, modelDetail, isDelete, new Stack<object>());
        }
        [UnconditionalSuppressMessage("AOT", "IL3050:Calling members annotated with 'RequiresDynamicCodeAttribute' may break functionality when AOT compiling.", Justification = "Only interface members reach MakeArrayType, models are reference types so the array code is shared.")]
        private static void MapRelated(ConcurrentFactoryDictionary<Type, object> store, object model, ModelDetail modelDetail, bool isDelete, Stack<object> stack)
        {
            foreach (var member in modelDetail.Members)
            {
                if (!isDelete && member.IsRelated)
                    LinkRelated(store, model, modelDetail, member);

                foreach (var foreignReference in member.ForeignReferences)
                {
                    if (store.TryGetValue(foreignReference.Type, out var sourceObject))
                    {
                        var source = (IList)sourceObject;

                        var foreignId = member.GetterBoxed!(model);
                        var relatedEnumerable = source.Cast<object>().Where(x => ModelAnalyzer.CompareIdentities(foreignId, ModelAnalyzer.GetIdentity(foreignReference.Type, x)));
                        foreach (var related in relatedEnumerable)
                        {
                            if (!stack.Contains(related))
                            {
                                stack.Push(related);
                                MapRelated(store, related, foreignReference, false, stack);
                                _ = stack.Pop();
                            }
                        }
                    }
                }
            }
        }
        [UnconditionalSuppressMessage("AOT", "IL3050:Calling members annotated with 'RequiresDynamicCodeAttribute' may break functionality when AOT compiling.", Justification = "@@JUSTIFY@@")]
        private static void LinkRelated(ConcurrentFactoryDictionary<Type, object> store, object model, ModelDetail modelDetail, ModelMemberDetail member)
        {
                {
                    //a related type nothing was stored for yet has no list; the relation is then empty rather than null so queries over it behave as in a database
                    var source = store.TryGetValue(member.ActualType, out var sourceObject) ? (IList)sourceObject : Array.Empty<object>();

                    if (member.IsEnumerable)
                    {
                        var id = ModelAnalyzer.GetIdentity(modelDetail.Type, model);
                        var relatedEnumerable = source.Cast<object>().Where(x => ModelAnalyzer.CompareIdentities(id, ModelAnalyzer.GetForeignIdentity(member.ActualType, member.ForeignIdentity!, x)));
                        //collections with a creator (List<T>) are filled directly, arrays and the interfaces an array satisfies are filled as arrays
                        if (member.MemberDetail.TypeDetail.HasCreator)
                        {
                            var list = (IList)member.CreatorBoxed();
                            foreach (var related in relatedEnumerable)
                                _ = list.Add(related);
                            member.SetterBoxed(model, list);
                        }
                        else
                        {
                            var matches = relatedEnumerable.ToArray();
                            var array = Array.CreateInstanceFromArrayType(member.Type.IsArray ? member.Type : member.ActualType.MakeArrayType(), matches.Length);
                            for (var i = 0; i < matches.Length; i++)
                                array.SetValue(matches[i], i);
                            member.SetterBoxed(model, array);
                        }
                    }
                    else
                    {
                        var foreignId = ModelAnalyzer.GetForeignIdentity(modelDetail.Type, member.ForeignIdentity!, model);
                        var related = source.Cast<object>().FirstOrDefault(x => ModelAnalyzer.CompareIdentities(foreignId, ModelAnalyzer.GetIdentity(member.ActualType, x)));
                        member.SetterBoxed(model, related);
                    }
                }

        }
    }
