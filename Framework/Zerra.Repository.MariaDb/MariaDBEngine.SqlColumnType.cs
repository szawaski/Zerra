namespace Zerra.Repository.MariaDb
{
    public sealed partial class MariaDbEngine
    {
        private sealed class SqlColumnType
        {
            public string Table { get; set; } = null!;
            public string Column { get; set; } = null!;
            public string DataType { get; set; } = null!;
            public bool IsNullable { get; set; }
            public long? CharacterMaximumLength { get; set; }
            public uint? NumericPrecision { get; set; }
            public uint? NumericScale { get; set; }
            public uint? DatetimePrecision { get; set; }
            public bool IsAutoGenerated { get; set; }
            public bool IsPrimaryKey { get; set; }
            public string? ColumnDefault { get; set; }
            public string? Extra { get; set; }

            public SqlColumnType WithNullable(bool isNullable)
            {
                var copy = (SqlColumnType)MemberwiseClone();
                copy.IsNullable = isNullable;
                return copy;
            }
        }
    }
}