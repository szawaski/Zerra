        }
        private SqlIndex[] GetSqlIndexes(ModelDetail model)
        {
            var query = $@"SELECT I.name, I.is_unique, CAST(CASE WHEN I.type = 1 THEN 1 ELSE 0 END AS bit), I.filter_definition, C.name, IC.is_descending_key
FROM sys.indexes I
JOIN sys.index_columns IC ON IC.object_id = I.object_id AND IC.index_id = I.index_id
JOIN sys.columns C ON C.object_id = IC.object_id AND C.column_id = IC.column_id
WHERE I.object_id = OBJECT_ID('[{model.DataSourceEntityName}]') AND I.type IN (1, 2) AND I.is_primary_key = 0 AND I.is_unique_constraint = 0 AND I.is_hypothetical = 0 AND IC.is_included_column = 0
ORDER BY I.name, IC.key_ordinal";

            var sqlIndexes = new List<SqlIndex>();
            SqlIndex? sqlIndex = null;
            foreach (var x in ExecuteSqlQuery(query).Select(x => (IList<object>)x))
            {
                var name = (string)x[0];
                if (sqlIndex is null || sqlIndex.Name != name)
                {
                    sqlIndex = new SqlIndex()
                    {
                        Name = name,
                        Columns = new(),
                        Descending = new(),
                        IsUnique = (bool)x[1],
                        IsClustered = (bool)x[2],
                        FilterDefinition = x[3] != DBNull.Value ? (string)x[3] : null,
                    };
                    sqlIndexes.Add(sqlIndex);
                }
