        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlInsert<TModel>(TModel model, Graph? graph, ModelDetail modelDetail, bool getIdentities, List<object> parameters) where TModel : class, new()
        {
            var sbColumns = new CharWriter();
            var sbValues = new CharWriter();
            try
            {
                GenerateSqlInsertRow(model, graph, modelDetail, ref sbColumns, ref sbValues, parameters);

                string sql;
                if (getIdentities)
                {
                    var sbOutput = new CharWriter();
                    try
                    {
                        foreach (var modelPropertyDetail in modelDetail.IdentityAutoGeneratedMembers)
                        {
                            var isProperty = graph is null || graph.HasMember(modelPropertyDetail.Name);
                            if (!modelPropertyDetail.IsNullable || isProperty)
                            {
                                object? value;
                                if (isProperty)
                                    value = modelPropertyDetail.GetterBoxed(model);
                                else
                                    value = modelPropertyDetail.CreatorBoxed();

                                if (value is not null)
                                {
                                    var property = modelPropertyDetail.StoreName;

                                    if (sbOutput.Length > 0)
                                        sbOutput.Write(',');
                                    sbOutput.Write("INSERTED.");
                                    sbOutput.Write(property);
                                }
                            }
                        }

                        if (sbColumns.Length > 0 && sbValues.Length > 0)
                            sql = $"INSERT INTO {(modelDetail.DataSourceSchemaName is null ? null : $"[{modelDetail.DataSourceSchemaName}].")}[{modelDetail.DataSourceEntityName}] ({sbColumns.ToString()}) OUTPUT ({sbOutput.ToString()}) VALUES ({sbValues.ToString()})";
                        else
                            sql = $"INSERT INTO {(modelDetail.DataSourceSchemaName is null ? null : $"[{modelDetail.DataSourceSchemaName}].")}[{modelDetail.DataSourceEntityName}] OUTPUT ({sbOutput.ToString()}) DEFAULT VALUES";
                    }
                    finally
                    {
                        sbOutput.Dispose();
                    }
                }
                else
                {
                    if (sbColumns.Length > 0 && sbValues.Length > 0)
                        sql = $"INSERT INTO {(modelDetail.DataSourceSchemaName is null ? null : $"[{modelDetail.DataSourceSchemaName}].")}[{modelDetail.DataSourceEntityName}] ({sbColumns.ToString()}) VALUES ({sbValues.ToString()})";
                    else
                        sql = $"INSERT INTO {(modelDetail.DataSourceSchemaName is null ? null : $"[{modelDetail.DataSourceSchemaName}].")}[{modelDetail.DataSourceEntityName}] DEFAULT VALUES";
                }
                return sql;
            }
            finally
            {
                sbColumns.Dispose();
                sbValues.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static void GenerateSqlInsertRow<TModel>(TModel model, Graph? graph, ModelDetail modelDetail, ref CharWriter sbColumns, ref CharWriter sbValues, List<object> parameters) where TModel : class, new()
        {
            foreach (var modelPropertyDetail in modelDetail.NonAutoGeneratedNonRelationMembers)
            {
                var isProperty = graph is null || graph.HasMember(modelPropertyDetail.Name);
                if (!modelPropertyDetail.IsNullable || isProperty)
                {
                    object? value;
                    if (isProperty)
                        value = modelPropertyDetail.GetterBoxed(model);
                    else
                        value = modelPropertyDetail.CreatorBoxed();

                    if (value is not null)
                    {
                        var property = modelPropertyDetail.StoreName;

                        if (sbColumns.Length > 0)
                            sbColumns.Write(',');
                        sbColumns.Write('[');
                        sbColumns.Write(property);
                        sbColumns.Write(']');

                        if (sbValues.Length > 0)
                            sbValues.Write(',');
                        AppendSqlValue(ref sbValues, modelPropertyDetail, value, false, false, parameters);
                    }
                }
            }
        }
        //consecutive models writing the same columns share a statement, up to the rows SQL Server takes in one VALUES and the parameters it takes in one command
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlInsertMany<TModel>(object[] models, ref int index, Graph? graph, ModelDetail modelDetail, List<object> parameters) where TModel : class, new()
        {
            var columnCount = modelDetail.NonAutoGeneratedNonRelationMembers.Count;
            var sb = new CharWriter();
            var sbColumns = new CharWriter();
            var sbValues = new CharWriter();
            var sbRowColumns = new CharWriter();
            try
            {
                GenerateSqlInsertRow((TModel)models[index], graph, modelDetail, ref sbColumns, ref sbValues, parameters);
                index++;
                if (sbColumns.Length == 0)
                    return $"INSERT INTO {(modelDetail.DataSourceSchemaName is null ? null : $"[{modelDetail.DataSourceSchemaName}].")}[{modelDetail.DataSourceEntityName}] DEFAULT VALUES";

                sb.Write("INSERT INTO [");
                if (modelDetail.DataSourceSchemaName is not null)
                {
                    sb.Write(modelDetail.DataSourceSchemaName);
                    sb.Write("].[");
                }
                sb.Write(modelDetail.DataSourceEntityName);
                sb.Write("] (");
                sb.Write(sbColumns);
                sb.Write(") VALUES (");
                sb.Write(sbValues);
                sb.Write(')');

                var rows = 1;
                while (index < models.Length && rows < 1000 && parameters.Count + columnCount <= batchParameters)
                {
                    sbRowColumns.Clear();
                    sbValues.Clear();
                    var parameterCount = parameters.Count;
                    GenerateSqlInsertRow((TModel)models[index], graph, modelDetail, ref sbRowColumns, ref sbValues, parameters);
                    if (!sbRowColumns.ToSpan().SequenceEqual(sbColumns.ToSpan()))
                    {
                        parameters.RemoveRange(parameterCount, parameters.Count - parameterCount);
                        break;
                    }
                    sb.Write(",(");
                    sb.Write(sbValues);
                    sb.Write(')');
                    rows++;
                    index++;
                }
                return sb.ToString();
            }
            finally
            {
                sbRowColumns.Dispose();
                sbValues.Dispose();
                sbColumns.Dispose();
                sb.Dispose();
            }
        }
        //each insert returning its identities is its own statement, the results come back in the order of the statements where the rows of one statement could come back in any order
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlInsertManyGetIdentities<TModel>(object[] models, ref int index, Graph? graph, ModelDetail modelDetail, List<object> parameters) where TModel : class, new()
        {
            var columnCount = modelDetail.NonAutoGeneratedNonRelationMembers.Count;
            var sb = new CharWriter();
            try
            {
                do
                {
                    if (sb.Length > 0)
                        sb.Write(";\r\n");
                    sb.Write(GenerateSqlInsert((TModel)models[index], graph, modelDetail, true, parameters));
                    index++;
                }
                while (index < models.Length && parameters.Count + columnCount <= batchParameters);
                return sb.ToString();
            }
            finally
            {
                sb.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlUpdateMany<TModel>(object[] models, ref int index, Graph? graph, ModelDetail modelDetail, List<object> parameters) where TModel : class, new()
        {
            var columnCount = modelDetail.NonAutoGeneratedNonRelationMembers.Count + modelDetail.IdentityMembers.Count;
            var sb = new CharWriter();
            try
            {
                do
                {
                    var sql = GenerateSqlUpdate((TModel)models[index], graph, modelDetail, parameters);
                    index++;
                    if (sql is null)
                        continue;
                    if (sb.Length > 0)
                        sb.Write(";\r\n");
                    sb.Write(sql);
                }
                while (index < models.Length && parameters.Count + columnCount <= batchParameters);
                return sb.ToString();
            }
            finally
            {
                sb.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string? GenerateSqlUpdate<TModel>(TModel model, Graph? graph, ModelDetail modelDetail, List<object> parameters) where TModel : class, new()
        {
            if (modelDetail.IdentityMembers.Count == 0)
                return null;

            var writer = new CharWriter();
            try
            {
                writer.Write("UPDATE [");
                if (modelDetail.DataSourceSchemaName is not null)
                {
                    writer.Write(modelDetail.DataSourceSchemaName);
                    writer.Write("].[");
                }
                writer.Write(modelDetail.DataSourceEntityName);
                writer.Write("] SET ");
                var first = true;
                foreach (var modelPropertyInfo in modelDetail.NonAutoGeneratedNonRelationMembers)
                {
                    if (graph is null || graph.HasMember(modelPropertyInfo.Name))
                    {
                        var value = modelPropertyInfo.GetterBoxed(model);
                        var property = modelPropertyInfo.StoreName;

                        if (first)
                            first = false;
                        else
                            writer.Write(',');
                        writer.Write('[');
                        writer.Write(property);
                        writer.Write(']');
                        AppendSqlValue(ref writer, modelPropertyInfo, value, true, false, parameters);
                    }
                }

                if (writer.Length == 0)
                    return null;

                writer.Write(" WHERE ");

                first = true;
                foreach (var modelPropertyInfo in modelDetail.IdentityMembers)
                {
                    var value = modelPropertyInfo.GetterBoxed(model);
                    var property = modelPropertyInfo.StoreName;

                    if (first)
                        first = false;
                    else
                        writer.Write(" AND ");
                    writer.Write('[');
                    writer.Write(property);
                    writer.Write(']');
                    AppendSqlValue(ref writer, modelPropertyInfo, value, false, true, parameters);
                }

                return writer.ToString();
            }
            finally
            {
                writer.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string GenerateSqlDelete(ICollection ids, ModelDetail modelDetail, List<object> parameters)
        {
            var sbWhere = new CharWriter();
            try
            {
                sbWhere.Write($"DELETE FROM [");
                if (modelDetail.DataSourceSchemaName is not null)
                {
                    sbWhere.Write(modelDetail.DataSourceSchemaName);
                    sbWhere.Write("].[");
                }
                sbWhere.Write(modelDetail.DataSourceEntityName);
                sbWhere.Write("] WHERE ");

                if (modelDetail.IdentityMembers.Count == 1)
                {
                    var modelPropertyInfo = modelDetail.IdentityMembers[0];
                    sbWhere.Write('[');
                    sbWhere.Write(modelPropertyInfo.StoreName);
                    sbWhere.Write("] IN (");

                    var first = true;
                    foreach (var id in ids)
                    {
                        if (first)
                            first = false;
                        else
                            sbWhere.Write(',');
                        AppendSqlValue(ref sbWhere, modelPropertyInfo, id, false, false, parameters);
                    }

                    sbWhere.Write(')');
                }
                else
                {
                    var first = true;
                    foreach (var id in ids)
                    {
                        if (first)
                            first = false;
                        else
                            sbWhere.Write(" OR ");
                        sbWhere.Write('(');

                        var idArray = ((ICollection)id).Cast<object>().ToArray();

                        var i = 0;
                        foreach (var modelPropertyInfo in modelDetail.IdentityMembers)
                        {
                            var value = idArray[i];

                            if (i > 0)
                                sbWhere.Write(" AND ");
                            sbWhere.Write('[');
                            sbWhere.Write(modelPropertyInfo.StoreName);
                            sbWhere.Write(']');
                            AppendSqlValue(ref sbWhere, modelPropertyInfo, value, false, true, parameters);
                            i++;
                        }
                        sbWhere.Write(')');
                    }
                }

                return sbWhere.ToString();
            }
            finally
            {
                sbWhere.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static string? GenerateSqlUpdateWhere<TModel>(TModel model, Graph graph, ModelDetail modelDetail, string sqlWhere, List<object> parameters) where TModel : class, new()
        {
            var writer = new CharWriter();
            try
            {
                writer.Write("UPDATE [");
                if (modelDetail.DataSourceSchemaName is not null)
                {
                    writer.Write(modelDetail.DataSourceSchemaName);
                    writer.Write("].[");
                }
                writer.Write(modelDetail.DataSourceEntityName);
                writer.Write("] SET ");
                var first = true;
                foreach (var modelPropertyInfo in modelDetail.NonAutoGeneratedNonRelationMembers)
                {
                    if (!graph.HasMember(modelPropertyInfo.Name))
                        continue;
                    var value = modelPropertyInfo.GetterBoxed(model);

                    if (first)
                        first = false;
                    else
                        writer.Write(',');
                    writer.Write('[');
                    writer.Write(modelPropertyInfo.StoreName);
                    writer.Write(']');
                    AppendSqlValue(ref writer, modelPropertyInfo, value, true, false, parameters);
                }

                if (first)
                    return null;

                writer.Write(sqlWhere);
                return writer.ToString();
            }
            finally
            {
                writer.Dispose();
            }
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private static void AppendSqlValue(ref CharWriter writer, ModelMemberDetail modelPropertyDetail, object? value, bool assigningValue, bool comparingValue, List<object> parameters)
        {
            if (value is null)
            {
                if (assigningValue)
                    writer.Write("=NULL");
                else if (comparingValue)
                    writer.Write("IS NULL");
                else
                    writer.Write("NULL");
                return;
            }

            //a value is a parameter so the plan of the statement serves any value; a boolean has two and stays in the statement
            if (parameters.Count < maxParameters && (modelPropertyDetail.EnumType is not null || modelPropertyDetail.Type == typeof(byte[]) || (modelPropertyDetail.CoreType.HasValue && modelPropertyDetail.CoreType.Value is not (CoreType.Boolean or CoreType.BooleanNullable))))
            {
                object parameter;
                if (modelPropertyDetail.EnumType is not null)
                {
                    parameter = EnumName.GetName(modelPropertyDetail.EnumType, value);
                }
                else if (modelPropertyDetail.CoreType is CoreType.Char or CoreType.CharNullable)
                {
                    parameter = ((char)value).ToString();
                }
                else if (modelPropertyDetail.CoreType is CoreType.DateTime or CoreType.DateTimeNullable)
                {
                    //as text, which converts to the column's datetime, datetime2, or date, with every digit only for datetime2 since datetime refuses more than three
                    var text = new CharWriter();
                    try
                    {
                        text.Write((DateTime)value, modelPropertyDetail.DatePart == StoreDatePart.DateTime && modelPropertyDetail.DataSourcePrecisionLength.HasValue ? CharWriter.DateTimeFormat.MsSqlDateTime2 : CharWriter.DateTimeFormat.MsSql);
                        parameter = text.ToString();
                    }
                    finally
                    {
                        text.Dispose();
                    }
                }
                else
                {
                    parameter = value;
                }
                if (assigningValue || comparingValue)
                    writer.Write('=');
                writer.Write("@p");
                writer.Write(parameters.Count);
                parameters.Add(parameter);
                return;
            }

            if (modelPropertyDetail.EnumType is not null)
            {
                if (assigningValue || comparingValue)
                    writer.Write('=');
                writer.Write("N'");
                writer.Write(EnumName.GetName(modelPropertyDetail.EnumType, value).Replace("'", "''"));
                writer.Write('\'');
                return;
            }

            if (modelPropertyDetail.CoreType.HasValue)
            {
                if (assigningValue || comparingValue)
                    writer.Write('=');
                switch (modelPropertyDetail.CoreType.Value)
                {
                    case CoreType.String:
                        writer.Write("N'");
                        writer.Write(((string)value).Replace("'", "''"));
                        writer.Write('\'');
                        return;

                    case CoreType.Boolean:
                    case CoreType.BooleanNullable:
                        writer.Write((bool)value == false ? '0' : '1');
                        return;
                    case CoreType.Byte:
                    case CoreType.ByteNullable:
                        writer.Write((byte)value);
                        return;
                    case CoreType.Int16:
                    case CoreType.Int16Nullable:
                        writer.Write((short)value);
                        return;
                    case CoreType.Int32:
                    case CoreType.Int32Nullable:
                        writer.Write((int)value);
                        return;
                    case CoreType.Int64:
                    case CoreType.Int64Nullable:
                        writer.Write((long)value);
                        return;
                    case CoreType.Single:
                    case CoreType.SingleNullable:
                        writer.Write((float)value);
                        return;
                    case CoreType.Double:
                    case CoreType.DoubleNullable:
                        writer.Write((double)value);
                        return;
                    case CoreType.Decimal:
                    case CoreType.DecimalNullable:
                        writer.Write((decimal)value);
                        return;
                    case CoreType.Char:
                    case CoreType.CharNullable:
                        writer.Write("N'");
                        var castedChar = (char)value;
                        if (castedChar == '\'')
                            writer.Write("''");
                        else
                            writer.Write(castedChar);
                        writer.Write('\'');
                        return;
                    case CoreType.DateTime:
                    case CoreType.DateTimeNullable:
                        writer.Write('\'');
                        writer.Write((DateTime)value, modelPropertyDetail.DatePart == StoreDatePart.DateTime && modelPropertyDetail.DataSourcePrecisionLength.HasValue ? CharWriter.DateTimeFormat.MsSqlDateTime2 : CharWriter.DateTimeFormat.MsSql);
                        writer.Write('\'');
                        return;
                    case CoreType.DateTimeOffset:
                    case CoreType.DateTimeOffsetNullable:
                        writer.Write('\'');
                        writer.Write((DateTimeOffset)value, CharWriter.DateTimeFormat.MsSql);
                        writer.Write('\'');
                        return;
                    case CoreType.TimeSpan:
                    case CoreType.TimeSpanNullable:
                        writer.Write('\'');
                        writer.Write((TimeSpan)value, CharWriter.TimeFormat.MsSql);
                        writer.Write('\'');
                        return;
                    case CoreType.DateOnly:
                    case CoreType.DateOnlyNullable:
                        writer.Write('\'');
                        writer.Write((DateOnly)value, CharWriter.DateTimeFormat.MsSql);
                        writer.Write('\'');
                        return;
                    case CoreType.TimeOnly:
                    case CoreType.TimeOnlyNullable:
                        writer.Write('\'');
                        writer.Write((TimeOnly)value, CharWriter.TimeFormat.MsSql);
                        writer.Write('\'');
                        return;
                    case CoreType.Guid:
                    case CoreType.GuidNullable:
                        writer.Write('\'');
                        writer.Write((Guid)value);
                        writer.Write('\'');
                        return;

                    default:
                        throw new NotImplementedException();
                }
            }

            if (modelPropertyDetail.Type == typeof(byte[]))
            {
                if (assigningValue || comparingValue)
                    writer.Write('=');
                writer.Write("0x");
                writer.Write((byte[])value, CharWriter.ByteFormat.Hex);
                return;
            }

            throw new Exception($"Cannot convert type to SQL value {modelPropertyDetail.Type.Name}");
        }

        //SQL Server takes up to 2100 parameters, past which values are written into the statement
        private const int maxParameters = 2000;
        private static readonly string[] parameterNames = new string[maxParameters];
        //SQL Server takes longer for each parameter the more a command has, 2000 cost 25 ms where 100 cost 0.4, so the commands of many models are small ones in one transaction
        private const int batchParameters = 128;
        //each value as the type the statement would have given its text, a string at the size of every string so the plan is the same for any length, a time at the 7 digits of its text where SqlClient would round it to fewer
        private static PooledParameters AddParameters(SqlCommand command, List<object>? parameters)
        {
            if (parameters is null || parameters.Count == 0)
                return default;
            for (var i = 0; i < parameters.Count; i++)
            {
                var value = parameters[i];
                var name = parameterNames[i] ??= "@p" + i.ToString(CultureInfo.InvariantCulture);
                SqlDbType type;
                var size = 0;
                byte precision = 0;
                byte scale = 0;
                switch (value)
                {
                    case string text: type = SqlDbType.NVarChar; size = text.Length <= 4000 ? 4000 : -1; break;
                    case int: type = SqlDbType.Int; break;
                    case long: type = SqlDbType.BigInt; break;
                    case Guid: type = SqlDbType.UniqueIdentifier; break;
                    //the value's scale with room for 10 or 29 whole digits, so a few plans serve every value, where a precision of 29 or more grew past SQL Server's 38 in arithmetic and lost the scale
                    case decimal number:
                        type = SqlDbType.Decimal;
                        scale = number.Scale;
                        precision = (byte)Math.Min(38, scale + (Math.Abs(decimal.Truncate(number)) < 10_000_000_000m ? 10 : 29));
                        break;
                    case short: type = SqlDbType.SmallInt; break;
                    case byte: type = SqlDbType.TinyInt; break;
                    case double: type = SqlDbType.Float; break;
                    case float: type = SqlDbType.Real; break;
                    case DateTimeOffset: type = SqlDbType.DateTimeOffset; scale = 7; break;
                    case TimeSpan: type = SqlDbType.Time; scale = 7; break;
                    case DateOnly: type = SqlDbType.Date; break;
                    case TimeOnly: type = SqlDbType.Time; scale = 7; break;
                    case byte[] bytes: type = SqlDbType.VarBinary; size = bytes.Length <= 8000 ? 8000 : -1; break;
                    default: throw new NotSupportedException($"{value.GetType().Name} is not a parameter type");
                }
                SqlParameter? parameter;
                lock (parameterPool)
                    _ = parameterPool.TryPop(out parameter);
                parameter ??= new SqlParameter();
                parameter.ParameterName = name;
                parameter.SqlDbType = type;
                parameter.Size = size;
                parameter.Precision = precision;
                parameter.Scale = scale;
                parameter.Value = value;
                _ = command.Parameters.Add(parameter);
            }
            return new PooledParameters(command);
        }
        //a parameter is a large object, so those of a finished command are kept for the next, shared as an async command finishes on another thread than it started on
        private static readonly Stack<SqlParameter> parameterPool = new();
        private const int parameterPoolSize = 512;
        private readonly struct PooledParameters : IDisposable
        {
            private readonly SqlCommand? command;
            public PooledParameters(SqlCommand command)
            {
                this.command = command;
            }
            public void Dispose()
            {
                if (command is null)
                    return;
                var parameters = command.Parameters;
                lock (parameterPool)
                {
                    for (var i = 0; i < parameters.Count && parameterPool.Count < parameterPoolSize; i++)
                    {
                        var parameter = parameters[i];
                        parameter.Value = null;
                        parameterPool.Push(parameter);
                    }
                    //cleared before the lock is released, SqlClient rejects a parameter another command takes from the pool while it's still in this one
                    parameters.Clear();
                }
            }
        }

        /// <inheritdoc />
        public bool SupportsTransactions => true;

        //the connection of an operation, which is the transaction's when there is one and closes with the operation when not
        private readonly struct EngineConnection : IDisposable
        {
            private readonly SqlConnection connection;
            private readonly SqlTransaction? transaction;
            private readonly RepoTransactionPart? part;
            public EngineConnection(SqlConnection connection, SqlTransaction? transaction, RepoTransactionPart? part)
            {
                this.connection = connection;
                this.transaction = transaction;
                this.part = part;
            }
            public SqlCommand CreateCommand()
            {
                var command = connection.CreateCommand();
                command.Transaction = transaction;
                return command;
            }
            public SqlCommand CreateCommand(SqlTransaction? local)
            {
                var command = connection.CreateCommand();
                command.Transaction = local ?? transaction;
                return command;
            }
            public SqlTransaction? BeginWhenNone() => transaction is null ? connection.BeginTransaction() : null;
            public async ValueTask<SqlTransaction?> BeginWhenNoneAsync(CancellationToken cancellationToken) => transaction is null ? (SqlTransaction)await connection.BeginTransactionAsync(cancellationToken) : null;
            public void HoldForStream() => part?.HoldForStream();
            public void Dispose()
            {
                if (part is null)
                    connection.Dispose();
                else
                    part.Exit();
            }
        }
        private EngineConnection OpenConnection()
        {
            var transaction = RepoTransaction.Current;
            if (transaction is not null)
            {
                var part = transaction.Enter(connectionString, nameof(MsSqlEngine), BeginTransactionPart);
                return new EngineConnection((SqlConnection)part.Connection, (SqlTransaction)part.Transaction, part);
            }
            var connection = new SqlConnection(connectionString);
            try
            {
                connection.Open();
            }
            catch
            {
                connection.Dispose();
                throw;
            }
            return new EngineConnection(connection, null, null);
        }
        private async ValueTask<EngineConnection> OpenConnectionAsync(CancellationToken cancellationToken)
        {
            var transaction = RepoTransaction.Current;
            if (transaction is not null)
            {
                var part = await transaction.EnterAsync(connectionString, nameof(MsSqlEngine), BeginTransactionPartAsync, cancellationToken);
                return new EngineConnection((SqlConnection)part.Connection, (SqlTransaction)part.Transaction, part);
            }
            var connection = new SqlConnection(connectionString);
            try
            {
                await connection.OpenAsync(cancellationToken);
            }
            catch
            {
                connection.Dispose();
                throw;
            }
            return new EngineConnection(connection, null, null);
        }
        private DbRepoTransactionPart BeginTransactionPart(IsolationLevel isolationLevel)
        {
            var connection = new SqlConnection(connectionString);
            try
            {
                connection.Open();
                return new DbRepoTransactionPart(connection, connection.BeginTransaction(isolationLevel));
            }
            catch
            {
                connection.Dispose();
                throw;
            }
        }
        private async Task<DbRepoTransactionPart> BeginTransactionPartAsync(IsolationLevel isolationLevel, CancellationToken cancellationToken)
        {
            var connection = new SqlConnection(connectionString);
            try
            {
                await connection.OpenAsync(cancellationToken);
                return new DbRepoTransactionPart(connection, await connection.BeginTransactionAsync(isolationLevel, cancellationToken));
            }
            catch
            {
                connection.Dispose();
                throw;
            }
        }

        /// <inheritdoc />
        public object? ExecuteLinq<TModel, TResult>(LinqQuery query, ModelDetail modelDetail) where TModel : class, new()
        {
            var statement = LinqMsSqlConverter.ConvertLinq(query, modelDetail);

            using (var connection = OpenConnection())
            {
                switch (query.Terminal)
                {
                    case LinqTerminal.Any:
                        using (var command = connection.CreateCommand())
                        {
                            command.CommandTimeout = 0;
                            command.CommandText = statement.Sql;
                            using var pooled = AddParameters(command, statement.Parameters);
                            using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                                return reader.HasRows;
                        }
                    case LinqTerminal.Count:
                    case LinqTerminal.LongCount:
                    case LinqTerminal.Sum:
                    case LinqTerminal.Min:
                    case LinqTerminal.Max:
                    case LinqTerminal.Average:
                        using (var command = connection.CreateCommand())
                        {
                            command.CommandTimeout = 0;
                            command.CommandText = statement.Sql;
                            using var pooled = AddParameters(command, statement.Parameters);
                            var value = command.ExecuteScalar();
                            if (value is null || value is DBNull)
                                return null;
                            return ConvertLinqValue(value, typeof(TResult));
                        }
                    default:
                        {
                            var results = query.Take is int take && take <= 1024 ? new List<TResult>(take) : new List<TResult>();
                            using (var command = connection.CreateCommand())
                            {
                                command.CommandTimeout = 0;
                                command.CommandText = LinqBatch(statement);
                                using var pooled = AddParameters(command, statement.Parameters);
                                using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                                {
                                    var pieces = ReadLinqPieces(reader, statement);
                                    var shape = statement.Plan.Shape!;
                                    while (reader.Read())
                                        results.Add((TResult)ReadLinqElement(reader, shape, pieces)!);
                                }
                            }
                            return results;
                        }
                }
            }
        }
        //the statements of the relations go in one batch before the parents' statement, each relation's after its own relations', so all are one round trip
        private static string LinqBatch(LinqStatement statement)
        {
            if (statement.Pieces is null)
                return statement.Sql;
            var sb = new CharWriter();
            try
            {
                AppendLinqPieces(statement, ref sb);
                sb.Write(statement.Sql);
                return sb.ToString();
            }
            finally
            {
                sb.Dispose();
            }
        }
        private static void AppendLinqPieces(LinqStatement statement, ref CharWriter sb)
        {
            if (statement.Pieces is null)
                return;
            foreach (var piece in statement.Pieces)
            {
                AppendLinqPieces(piece, ref sb);
                sb.Write(piece.Sql);
                sb.Write(';');
            }
        }
        //the rows of each relation for all the parents at once, matched to them by the key, read before the parents so each element is built whole from its row
        private static LinqPieceElements[]? ReadLinqPieces(SqlDataReader reader, LinqStatement statement)
        {
            if (statement.Pieces is null)
                return null;
            var pieces = new LinqPieceElements[statement.Pieces.Length];
            for (var p = 0; p < pieces.Length; p++)
            {
                var piece = statement.Pieces[p];
                var piecePieces = ReadLinqPieces(reader, piece);
                var elements = statement.Plan.Pieces[p].NewElements();
                pieces[p] = elements;
                var shape = piece.Plan.Shape!;
                var keyColumn = piece.Plan.ParentKeyColumn!.Value;
                var keyColumns = statement.Plan.Pieces[p].CompositeKey ? piece.Plan.ParentKeyColumns : null;
                while (reader.Read())
                {
                    var element = ReadLinqElement(reader, shape, piecePieces);
                    if (keyColumns is null)
                        AddLinqPiece(reader, keyColumn, elements, element);
                    else if (LinqKey.Read(reader, keyColumns) is { } key)
                        elements.Add(key, element);
                }
                _ = reader.NextResult();
            }
            return pieces;
        }
        //a key read as its own type where the column holds it, so it isn't boxed for every row
        private static void AddLinqPiece(SqlDataReader reader, int column, LinqPieceElements elements, object? element)
        {
            if (reader.IsDBNull(column))
                return;
            var type = reader.GetFieldType(column);
            switch (elements)
            {
                case LinqPieceElements<Guid> guids when type == typeof(Guid): guids.Add(reader.GetGuid(column), element); return;
                case LinqPieceElements<int> ints when type == typeof(int): ints.Add(reader.GetInt32(column), element); return;
                case LinqPieceElements<long> longs when type == typeof(long): longs.Add(reader.GetInt64(column), element); return;
                case LinqPieceElements<string> texts when type == typeof(string): texts.Add(reader.GetString(column), element); return;
                default: elements.Add(reader.GetValue(column), element); return;
            }
        }
        private static List<object?>? FindLinqPiece(SqlDataReader reader, int column, LinqPieceElements elements)
        {
            if (reader.IsDBNull(column))
                return null;
            var type = reader.GetFieldType(column);
            switch (elements)
            {
                case LinqPieceElements<Guid> guids when type == typeof(Guid): return guids.Find(reader.GetGuid(column));
                case LinqPieceElements<int> ints when type == typeof(int): return ints.Find(reader.GetInt32(column));
                case LinqPieceElements<long> longs when type == typeof(long): return longs.Find(reader.GetInt64(column));
                case LinqPieceElements<string> texts when type == typeof(string): return texts.Find(reader.GetString(column));
                default: return elements.Find(reader.GetValue(column));
            }
        }
        private static object? ReadLinqElement(SqlDataReader reader, LinqShape shape, LinqPieceElements[]? pieces)
        {
            switch (shape.Kind)
            {
                case LinqShapeKind.Column:
                    return ReadLinqValue(reader, shape.Column!.Index, shape.Type);
                case LinqShapeKind.Model:
                    {
                        if (shape.JoinedKey is not null && reader.IsDBNull(shape.JoinedKey.Index))
                            return null;
                        var model = shape.Model!.Creator();
                        var members = shape.ModelMembers!;
                        var columns = shape.ModelColumns!;
                        for (var i = 0; i < members.Length; i++)
                        {
                            var member = members[i];
                            if (member.CoreType.HasValue)
                            {
                                ReadLinqMember(reader, columns[i].Index, member.CoreType.Value, member.Setter, model);
                            }
                            else if (member.Type == typeof(byte[]))
                            {
                                if (!reader.IsDBNull(columns[i].Index))
                                    ((Action<object, byte[]>)member.Setter)(model, reader.GetSqlBytes(columns[i].Index).Value);
                            }
                            else
                            {
                                var value = ReadLinqValue(reader, columns[i].Index, member.Type);
                                if (value is not null)
                                    member.SetterBoxed(model, value);
                            }
                        }
                        if (shape.ModelRelations is not null)
                        {
                            foreach (var relation in shape.ModelRelations)
                            {
                                var value = ReadLinqElement(reader, relation, pieces);
                                if (value is not null)
                                    relation.RelationMember!.SetterBoxed(model, value);
                            }
                        }
                        return model;
                    }
                case LinqShapeKind.Object:
                    {
                        if (shape.JoinedKey is not null && reader.IsDBNull(shape.JoinedKey.Index))
                            return null;
                        object instance;
                        if (shape.Arguments is null || shape.Arguments.Length == 0)
                        {
                            instance = shape.Constructor is null ? TypeAnalyzer.GetTypeDetail(shape.Type).CreatorBoxed!() : shape.Constructor.Invoke(Array.Empty<object>());
                        }
                        else
                        {
                            var arguments = shape.ArgumentValues();
                            for (var i = 0; i < arguments.Length; i++)
                                arguments[i] = ReadLinqElement(reader, shape.Arguments[i], pieces);
                            instance = shape.Construct(arguments);
                        }
                        if (shape.Members is not null)
                        {
                            for (var i = 0; i < shape.Members.Length; i++)
                            {
                                var member = shape.Members[i];
                                var value = shape.Values![i];
                                //a member set from a column of the model's type reads it typed, as the model's own members do
                                if (value.Kind == LinqShapeKind.Column && value.Column!.Member is { CoreType: not null } column && column.Type == member.Type && !value.Column.Optional)
                                {
                                    ReadLinqMember(reader, value.Column.Index, column.CoreType.Value, member.Setter!, instance);
                                    continue;
                                }
                                var element = ReadLinqElement(reader, value, pieces);
                                if (element is not null)
                                    member.SetterBoxed!(instance, element);
                            }
                        }
                        return instance;
                    }
                default:
                    {
                        return shape.BuildRelation(shape.Piece!.CompositeKey ? (LinqKey.Read(reader, shape.Piece.ParentColumns) is { } key ? pieces![shape.PieceIndex].Find(key) : null) : FindLinqPiece(reader, shape.Piece!.ParentColumn, pieces![shape.PieceIndex]));
                    }
            }
        }
        private static object? ReadLinqValue(SqlDataReader reader, int i, Type type)
        {
            if (reader.IsDBNull(i))
                return null;
            return ConvertLinqValue(reader.GetValue(i), type);
        }
        private static object? ConvertLinqValue(object value, Type type)
        {
            var valueType = value.GetType();
            var underlying = Nullable.GetUnderlyingType(type) ?? type;
            if (valueType == underlying)
                return value;
            if (underlying.IsEnum)
                return value is string text ? EnumName.Parse(text, underlying) : Enum.ToObject(underlying, Convert.ChangeType(value, Enum.GetUnderlyingType(underlying), CultureInfo.InvariantCulture));
            return TypeAnalyzer.Convert(value, type);
        }
        private static void ReadLinqMember(SqlDataReader reader, int i, CoreType coreType, Delegate setter, object instance)
        {
            switch (coreType)
            {
                case CoreType.Boolean:
                    ((Action<object, bool>)setter)(instance, reader.GetBoolean(i));
                    break;
                case CoreType.Byte:
                    ((Action<object, byte>)setter)(instance, reader.GetByte(i));
                    break;
                case CoreType.Int16:
                    ((Action<object, short>)setter)(instance, reader.GetInt16(i));
                    break;
                case CoreType.Int32:
                    ((Action<object, int>)setter)(instance, reader.GetInt32(i));
                    break;
                case CoreType.Int64:
                    ((Action<object, long>)setter)(instance, reader.GetInt64(i));
                    break;
                case CoreType.Single:
                    ((Action<object, float>)setter)(instance, reader.GetFloat(i));
                    break;
                case CoreType.Double:
                    ((Action<object, double>)setter)(instance, reader.GetDouble(i));
                    break;
                case CoreType.Decimal:
                    ((Action<object, decimal>)setter)(instance, reader.GetDecimal(i));
                    break;
                case CoreType.Char:
                    {
                        var sqlValue = reader.GetSqlString(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, char>)setter)(instance, sqlValue.Value[0]);
                    }
                    break;
                case CoreType.DateTime:
                    ((Action<object, DateTime>)setter)(instance, new DateTime(reader.GetDateTime(i).Ticks, DateTimeKind.Utc));
                    break;
                case CoreType.DateTimeOffset:
                    ((Action<object, DateTimeOffset>)setter)(instance, reader.GetDateTimeOffset(i));
                    break;
                case CoreType.TimeSpan:
                    ((Action<object, TimeSpan>)setter)(instance, reader.GetTimeSpan(i));
                    break;
                case CoreType.DateOnly:
                    ((Action<object, DateOnly>)setter)(instance, DateOnly.FromDateTime(reader.GetDateTime(i)));
                    break;
                case CoreType.TimeOnly:
                    ((Action<object, TimeOnly>)setter)(instance, TimeOnly.FromTimeSpan(reader.GetTimeSpan(i)));
                    break;
                case CoreType.Guid:
                    ((Action<object, Guid>)setter)(instance, reader.GetGuid(i));
                    break;
                case CoreType.String:
                    {
                        var sqlValue = reader.GetSqlString(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, string>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.BooleanNullable:
                    {
                        var sqlValue = reader.GetSqlBoolean(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, bool?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.ByteNullable:
                    {
                        var sqlValue = reader.GetSqlByte(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, byte?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.Int16Nullable:
                    {
                        var sqlValue = reader.GetSqlInt16(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, short?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.Int32Nullable:
                    {
                        var sqlValue = reader.GetSqlInt32(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, int?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.Int64Nullable:
                    {
                        var sqlValue = reader.GetSqlInt64(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, long?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.SingleNullable:
                    {
                        var sqlValue = reader.GetSqlSingle(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, float?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                case CoreType.DoubleNullable:
                    if (!reader.IsDBNull(i))  //GetSqlDouble doesn't handle SqlMoney
                        ((Action<object, double?>)setter)(instance, reader.GetDouble(i));
                    break;
                case CoreType.DecimalNullable:
                    if (!reader.IsDBNull(i))  //GetSqlDecimal doesn't handle SqlMoney
                        ((Action<object, decimal?>)setter)(instance, reader.GetDecimal(i));
                    break;
                case CoreType.CharNullable:
                    {
                        var sqlValue = reader.GetSqlChars(i);
                        if (!sqlValue.IsNull && sqlValue.Value.Length > 0)
                            ((Action<object, char?>)setter)(instance, sqlValue.Value[0]);
                    }
                    break;
                case CoreType.DateTimeNullable:
                    if (!reader.IsDBNull(i)) //GetSqlDateTime doesn't handle null
                        ((Action<object, DateTime?>)setter)(instance, new DateTime(reader.GetDateTime(i).Ticks, DateTimeKind.Utc));
                    break;
                case CoreType.DateTimeOffsetNullable:
                    if (!reader.IsDBNull(i))
                        ((Action<object, DateTimeOffset?>)setter)(instance, reader.GetDateTimeOffset(i));
                    break;
                case CoreType.TimeSpanNullable:
                    if (!reader.IsDBNull(i))
                        ((Action<object, TimeSpan?>)setter)(instance, reader.GetTimeSpan(i));
                    break;
                case CoreType.DateOnlyNullable:
                    if (!reader.IsDBNull(i))
                        ((Action<object, DateOnly?>)setter)(instance, DateOnly.FromDateTime(reader.GetDateTime(i)));
                    break;
                case CoreType.TimeOnlyNullable:
                    if (!reader.IsDBNull(i))
                        ((Action<object, TimeOnly?>)setter)(instance, TimeOnly.FromTimeSpan(reader.GetTimeSpan(i)));
                    break;
                case CoreType.GuidNullable:
                    {
                        var sqlValue = reader.GetSqlGuid(i);
                        if (!sqlValue.IsNull)
                            ((Action<object, Guid?>)setter)(instance, sqlValue.Value);
                    }
                    break;
                default:
                    throw new NotSupportedException($"{nameof(MsSqlEngine)} Cannot map to type {coreType}");
            }
        }

        /// <inheritdoc/>
        public async Task<object?> ExecuteLinqAsync<TModel, TResult>(LinqQuery query, ModelDetail modelDetail, CancellationToken cancellationToken = default) where TModel : class, new()
        {
            var statement = LinqMsSqlConverter.ConvertLinq(query, modelDetail);

            try
            {
                using (var connection = await OpenConnectionAsync(cancellationToken))
                {
                    switch (query.Terminal)
                    {
                        case LinqTerminal.Any:
                            using (var command = connection.CreateCommand())
                            {
                                command.CommandTimeout = 0;
                                command.CommandText = statement.Sql;
                                using var pooled = AddParameters(command, statement.Parameters);
                                using (var reader = await command.ExecuteReaderAsync(CommandBehavior.SequentialAccess, cancellationToken))
                                    return reader.HasRows;
                            }
                        case LinqTerminal.Count:
                        case LinqTerminal.LongCount:
                        case LinqTerminal.Sum:
                        case LinqTerminal.Min:
                        case LinqTerminal.Max:
                        case LinqTerminal.Average:
                            using (var command = connection.CreateCommand())
                            {
                                command.CommandTimeout = 0;
                                command.CommandText = statement.Sql;
                                using var pooled = AddParameters(command, statement.Parameters);
                                var value = await command.ExecuteScalarAsync(cancellationToken);
                                if (value is null || value is DBNull)
                                    return null;
                                return ConvertLinqValue(value, typeof(TResult));
                            }
                        default:
                            {
                                var results = query.Take is int take && take <= 1024 ? new List<TResult>(take) : new List<TResult>();
                                using (var command = connection.CreateCommand())
                                {
                                    command.CommandTimeout = 0;
                                    command.CommandText = LinqBatch(statement);
                                    using var pooled = AddParameters(command, statement.Parameters);
                                    using (var reader = await command.ExecuteReaderAsync(CommandBehavior.SequentialAccess, cancellationToken))
                                    {
                                        var pieces = await ReadLinqPiecesAsync(reader, statement, cancellationToken);
                                        var shape = statement.Plan.Shape!;
                                        while (await reader.ReadAsync(cancellationToken))
                                            results.Add((TResult)ReadLinqElement(reader, shape, pieces)!);
                                    }
                                }
                                return results;
                            }
                    }
                }
            }
            //SqlClient reports a command it cancelled as its own error
            catch (SqlException ex) when (cancellationToken.IsCancellationRequested)
            {
                throw new OperationCanceledException(ex.Message, ex, cancellationToken);
            }
        }
        /// <inheritdoc/>
        public IEnumerable<TResult> ExecuteLinqStream<TModel, TResult>(LinqQuery query, ModelDetail modelDetail) where TModel : class, new()
        {
            var statement = LinqMsSqlConverter.ConvertLinq(query, modelDetail);
            using var connection = OpenConnection();
            connection.HoldForStream();
            using var command = connection.CreateCommand();
            command.CommandTimeout = 0;
            command.CommandText = LinqBatch(statement);
            using var pooled = AddParameters(command, statement.Parameters);
            using var reader = command.ExecuteReader(CommandBehavior.SequentialAccess);
            var pieces = ReadLinqPieces(reader, statement);
            var shape = statement.Plan.Shape!;
            while (reader.Read())
                yield return (TResult)ReadLinqElement(reader, shape, pieces)!;
        }
        /// <inheritdoc/>
        public async IAsyncEnumerable<TResult> ExecuteLinqStreamAsync<TModel, TResult>(LinqQuery query, ModelDetail modelDetail, [EnumeratorCancellation] CancellationToken cancellationToken = default) where TModel : class, new()
        {
            var statement = LinqMsSqlConverter.ConvertLinq(query, modelDetail);
            using var connection = await OpenConnectionAsync(cancellationToken);
            connection.HoldForStream();
            using var command = connection.CreateCommand();
            command.CommandTimeout = 0;
            command.CommandText = LinqBatch(statement);
            using var pooled = AddParameters(command, statement.Parameters);
            SqlDataReader reader;
            LinqPieceElements[]? pieces;
            try
            {
                reader = await command.ExecuteReaderAsync(CommandBehavior.SequentialAccess, cancellationToken);
            }
            //SqlClient reports a command it cancelled as its own error
            catch (SqlException ex) when (cancellationToken.IsCancellationRequested)
            {
                throw new OperationCanceledException(ex.Message, ex, cancellationToken);
            }
            using (reader)
            {
                try
                {
                    pieces = await ReadLinqPiecesAsync(reader, statement, cancellationToken);
                }
                catch (SqlException ex) when (cancellationToken.IsCancellationRequested)
                {
                    throw new OperationCanceledException(ex.Message, ex, cancellationToken);
                }
                var shape = statement.Plan.Shape!;
                while (true)
                {
                    try
                    {
                        if (!await reader.ReadAsync(cancellationToken))
                            break;
                    }
                    catch (SqlException ex) when (cancellationToken.IsCancellationRequested)
                    {
                        throw new OperationCanceledException(ex.Message, ex, cancellationToken);
                    }
                    yield return (TResult)ReadLinqElement(reader, shape, pieces)!;
                }
            }
        }
        private static async Task<LinqPieceElements[]?> ReadLinqPiecesAsync(SqlDataReader reader, LinqStatement statement, CancellationToken cancellationToken)
        {
            if (statement.Pieces is null)
                return null;
            var pieces = new LinqPieceElements[statement.Pieces.Length];
            for (var p = 0; p < pieces.Length; p++)
            {
                var piece = statement.Pieces[p];
                var piecePieces = await ReadLinqPiecesAsync(reader, piece, cancellationToken);
                var elements = statement.Plan.Pieces[p].NewElements();
                pieces[p] = elements;
                var shape = piece.Plan.Shape!;
                var keyColumn = piece.Plan.ParentKeyColumn!.Value;
                var keyColumns = statement.Plan.Pieces[p].CompositeKey ? piece.Plan.ParentKeyColumns : null;
                while (await reader.ReadAsync(cancellationToken))
                {
                    var element = ReadLinqElement(reader, shape, piecePieces);
                    if (keyColumns is null)
                        AddLinqPiece(reader, keyColumn, elements, element);
                    else if (LinqKey.Read(reader, keyColumns) is { } key)
                        elements.Add(key, element);
                }
                _ = await reader.NextResultAsync(cancellationToken);
            }
            return pieces;
        }
