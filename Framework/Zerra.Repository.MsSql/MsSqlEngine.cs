        /// <inheritdoc/>
        public object[] ExecuteInsertManyGetIdentities<TModel>(object[] models, Graph? graph, ModelDetail modelDetail) where TModel : class, new()
        {
            var identities = new object[models.Length];
            using (var connection = OpenConnection())
            {
                var local = connection.BeginWhenNone();
                try
                {
                    var index = 0;
                    while (index < models.Length)
                    {
                        var start = index;
                        var parameters = new MsSqlParameterList();
                        var sql = GenerateSqlInsertManyGetIdentities<TModel>(models, ref index, graph, modelDetail, parameters);
                        using (var command = connection.CreateCommand(local))
                        {
                            command.CommandTimeout = 0;
                            command.CommandText = sql;
                            using var pooled = AddParameters(command, parameters);
                            using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                            {
                                for (var i = start; i < index; i++)
                                {
                                    if ((i > start && !reader.NextResult()) || !reader.Read())
                                        throw new Exception($"No rows returned from insert operation for model of type {typeof(TModel).Name}");
                                    identities[i] = ReadIdentities(reader);
                                }
                            }
                        }
                    }
                    local?.Commit();
                }
                finally
                {
                    local?.Dispose();
                }
            }
            return identities;
        }
