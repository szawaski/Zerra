        public object ExecuteInsertGetIdentities<TModel>(TModel model, Graph? graph, ModelDetail modelDetail) where TModel : class, new()
        {
            var parameters = new MsSqlParameterList();
            var sql = MsSqlEngine.GenerateSqlInsert(model, graph, modelDetail, true, parameters);

            using (var connection = OpenConnection())
            {
                using (var command = connection.CreateCommand())
                {
                    command.CommandTimeout = 0;
                    command.CommandText = sql;
                    using var pooled = AddParameters(command, parameters);
                    using (var reader = command.ExecuteReader(CommandBehavior.SequentialAccess))
                    {
                        if (reader.HasRows)
                        {
                            _ = reader.Read();

                            if (reader.FieldCount == 1)
                            {
                                var value = reader[0];
                                return value;
                            }
                            else
                            {
                                var values = new List<object>();
                                for (var i = 0; i < reader.FieldCount; i++)
                                {
                                    var value = reader[i];
                                    values.Add(value);
                                }
                                return values;
                            }
                        }
                    }
                }
            }

            throw new Exception($"No rows returned from insert operation for model of type {typeof(TModel).Name}");
        }
