        private static object ReadIdentities(SqlDataReader reader)
        {
            if (reader.FieldCount == 1)
                return reader[0];
            var values = new List<object>();
            for (var i = 0; i < reader.FieldCount; i++)
                values.Add(reader[i]);
            return values;
        }
