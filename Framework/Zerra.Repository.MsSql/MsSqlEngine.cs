        private bool AssureTable(bool create, List<string> sql, bool needCreateDatabase, ModelDetail model)
        {
            var nonIdentityColumns = model.Members.Where(x => !x.IsIdentity && !x.IsDataSourceEntity && x.ColumnCoreType.HasValue || x.Type == typeof(byte[])).ToArray();
            var identityColumns = model.Members.Where(x => x.IsIdentity).ToArray();

            if (nonIdentityColumns.Length + identityColumns.Length == 0)
                return false; //Cannot create table with no columns

            if (!needCreateDatabase)
            {
                var sqlQuery = $"SELECT COUNT(1) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME = '{model.DataSourceEntityName}' AND TABLE_SCHEMA = {(model.DataSourceSchemaName is null ? "SCHEMA_NAME()" : $"'{model.DataSourceSchemaName}'")}";
                var exists = ExecuteSqlScalar<int>(sqlQuery) > 0;
                if (exists)
                    return false;
            }

            if (create)
            {
                var sb = new StringBuilder();
                _ = sb.Append("CREATE TABLE ").Append(model.DataSourceSchemaName is null ? $"[{model.DataSourceEntityName}]" : $"[{model.DataSourceSchemaName}].[{model.DataSourceEntityName}]").Append("(\r\n");

                for (var i = 0; i < identityColumns.Length; i++)
                {
                    var property = identityColumns[i];
                    if (i > 0)
                        _ = sb.Append(",\r\n");
                    _ = sb.Append("\t[").Append(property.StoreName).Append("] ");
                    WriteSqlTypeFromModel(sb, property);
                }
                for (var i = 0; i < nonIdentityColumns.Length; i++)
                {
                    var property = nonIdentityColumns[i];
                    if (i > 0 || identityColumns.Length > 0)
                        _ = sb.Append(",\r\n");
                    _ = sb.Append("\t[").Append(property.StoreName).Append("] ");
                    WriteSqlTypeFromModel(sb, property);
                }
                if (identityColumns.Length > 0)
                {
                    _ = sb.Append("\r\n\tCONSTRAINT [PK_").Append(model.DataSourceEntityName).Append("] PRIMARY KEY CLUSTERED(\r\n");

                    for (var i = 0; i < identityColumns.Length; i++)
                    {
                        var property = identityColumns[i];
                        if (i > 0)
                            _ = sb.Append(",\r\n");
                        _ = sb.Append("\t\t[").Append(property.StoreName).Append("] ASC");
                    }
                    _ = sb.Append("\r\n\t)\r\n");
                }
                _ = sb.Append("\tON [PRIMARY]");
                _ = sb.Append("\r\n)");
                _ = sb.Append("\r\nON [PRIMARY]");

                sql.Add(sb.ToString());
            }

            return true;
        }

        private void AssureColumns(bool changeColumns, bool changeConstraints, bool dropColumns, List<string> sql, ModelDetail model, SqlColumnType[] sqlColumns, SqlConstraint[] sqlConstraints, HashSet<string> droppedConstraints, SqlIndex[] sqlIndexes, HashSet<SqlIndex> droppedIndexes)
        {
            var columns = model.Members.Where(x => !x.IsDataSourceEntity && x.ColumnCoreType.HasValue || x.Type == typeof(byte[])).ToArray();
            var table = model.DataSourceSchemaName is null ? $"[{model.DataSourceEntityName}]" : $"[{model.DataSourceSchemaName}].[{model.DataSourceEntityName}]";

            var sb = new StringBuilder();

            foreach (var column in columns)
            {
                var sqlColumn = sqlColumns.FirstOrDefault(x => x.Table == model.DataSourceEntityName && x.Column == column.StoreName);
                if (sqlColumn is null)
                {
                    if (changeColumns)
                    {
                        //without constraints a new column is nullable until they run, so the code writing the table before it still can
                        var nullable = !changeConstraints && !column.IsIdentity;
                        _ = sb.Append("ALTER TABLE ").Append(table).Append(" ADD [").Append(column.StoreName).Append("] ");
                        WriteSqlTypeFromModel(sb, column, nullable || !column.IsDataSourceNotNull);
                        var withDefault = !nullable && column.IsDataSourceNotNull && !column.IsIdentityAutoGenerated;
                        if (withDefault)
                        {
                            _ = sb.Append(" CONSTRAINT [DF_").Append(model.DataSourceEntityName).Append('_').Append(column.StoreName).Append("] DEFAULT ");
                            WriteDefaultValue(sb, column);
                        }
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                        if (withDefault)
                        {
                            _ = sb.Append("ALTER TABLE ").Append(table).Append(" DROP CONSTRAINT [DF_").Append(model.DataSourceEntityName).Append('_').Append(column.StoreName).Append(']');
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }
                    }
                }
                else
                {
                    if (changeColumns || changeConstraints)
                    {
                        var sameType = ModelMatchesSqlType(column, sqlColumn);
                        if (!sameType)
                        {
                            if (sqlColumn.IsPrimaryKey || sqlColumn.IsAutoGenerated || sqlColumn.IsPrimaryKey != column.IsIdentity || sqlColumn.IsAutoGenerated != column.IsIdentityAutoGenerated)
                                throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MsSqlEngine)} cannot automatically change column with a Primary Key or Identity {model.Type.Name}.{column.Name}");

                            var nullable = !column.IsDataSourceNotNull;
                            var typeMatches = ModelMatchesSqlType(column, sqlColumn.WithNullable(nullable));
                            if (!typeMatches && !ModelRelatesToSqlType(column, sqlColumn))
                                throw new InvalidOperationException($"{nameof(MsSqlEngine)} cannot change {model.Type.Name}.{column.Name} from {sqlColumn.DataType} to an unrelated type, add a new column and move the data instead");

                            //columns alone only widen a type and allow nulls, changes that never fail on the rows
                            if (!changeConstraints)
                            {
                                if (!typeMatches && !ModelWidensSqlType(column, sqlColumn))
                                    continue;
                                nullable = nullable || sqlColumn.IsNullable;
                                if (typeMatches && nullable == sqlColumn.IsNullable)
                                    continue;
                            }

                            var theseSqlConstraints = sqlConstraints.Where(x => (x.PK_Table == model.DataSourceEntityName && x.PK_Column == column.Name) || (x.FK_Table == model.DataSourceEntityName && x.FK_Column == column.Name)).ToArray();
                            if (theseSqlConstraints.Length > 0)
                            {
                                foreach (var sqlConstraint in theseSqlConstraints)
                                {
                                    if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                                        continue;
                                    _ = sb.Append("ALTER TABLE [").Append(sqlConstraint.FK_Schema).Append("].[").Append(sqlConstraint.FK_Table).Append("] DROP CONSTRAINT [").Append(sqlConstraint.FK_Name).Append(']');
                                    sql.Add(sb.ToString());
                                    _ = sb.Clear();
                                }
                            }

                            foreach (var sqlIndex in sqlIndexes)
                            {
                                if (!sqlIndex.Columns.Contains(column.StoreName, StringComparer.OrdinalIgnoreCase) || !droppedIndexes.Add(sqlIndex))
                                    continue;
                                _ = sb.Append("DROP INDEX [").Append(sqlIndex.Name).Append("] ON ").Append(table);
                                sql.Add(sb.ToString());
                                _ = sb.Clear();
                            }

                            var putBack = new List<string>();
                            DropColumnDependents(sql, putBack, table, column.StoreName);

                            _ = sb.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN [").Append(column.StoreName).Append("] ");
                            WriteSqlTypeFromModel(sb, column, nullable);
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                            sql.AddRange(putBack);
                        }
                    }
                }
            }

            if (dropColumns || changeColumns)
            {
                //columns not in model, a column has a row for each key it is in
                var droppedColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                foreach (var sqlColumn in sqlColumns.Where(x => x.Table == model.DataSourceEntityName))
                {
                    var column = columns.FirstOrDefault(x => x.StoreName == sqlColumn.Column);
                    if (column is not null || !droppedColumns.Add(sqlColumn.Column))
                        continue;

                    if (!dropColumns)
                    {
                        //kept until dropped, nullable so the code without it can write the table
                        if (sqlColumn.IsNullable)
                            continue;
                        if (sqlColumns.Any(x => x.Table == sqlColumn.Table && x.Column == sqlColumn.Column && (x.IsPrimaryKey || x.IsAutoGenerated)))
                            throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MsSqlEngine)} needs to make {sqlColumn.Table}.{sqlColumn.Column} nullable but cannot automatically change column with a Primary Key or Identity");

                        foreach (var sqlConstraint in sqlConstraints.Where(x => (x.PK_Table == sqlColumn.Table && x.PK_Column == sqlColumn.Column) || (x.FK_Table == sqlColumn.Table && x.FK_Column == sqlColumn.Column)))
                        {
                            if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                                continue;
                            _ = sb.Append("ALTER TABLE [").Append(sqlConstraint.FK_Schema).Append("].[").Append(sqlConstraint.FK_Table).Append("] DROP CONSTRAINT [").Append(sqlConstraint.FK_Name).Append(']');
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }

                        foreach (var sqlIndex in sqlIndexes)
                        {
                            if (!sqlIndex.Columns.Contains(sqlColumn.Column, StringComparer.OrdinalIgnoreCase) || !droppedIndexes.Add(sqlIndex))
                                continue;
                            _ = sb.Append("DROP INDEX [").Append(sqlIndex.Name).Append("] ON ").Append(table);
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }

                        var putBack = new List<string>();
                        DropColumnDependents(sql, putBack, table, sqlColumn.Column);

                        _ = sb.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN [").Append(sqlColumn.Column).Append("] ");
                        WriteSqlTypeFromColumn(sb, sqlColumn);
                        _ = sb.Append(" NULL");
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                        sql.AddRange(putBack);
                        continue;
                    }

                    if (sqlColumns.Any(x => x.Table == sqlColumn.Table && x.Column == sqlColumn.Column && x.IsPrimaryKey))
                        throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MsSqlEngine)} cannot automatically drop {sqlColumn.Table}.{sqlColumn.Column} in the Primary Key");

                    var theseSqlConstraints = sqlConstraints.Where(x => (x.PK_Table == sqlColumn.Table && x.PK_Column == sqlColumn.Column) || (x.FK_Table == sqlColumn.Table && x.FK_Column == sqlColumn.Column)).ToArray();
                    foreach (var sqlConstraint in theseSqlConstraints)
                    {
                        if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                            continue;
                        _ = sb.Append("ALTER TABLE [").Append(sqlConstraint.FK_Schema).Append("].[").Append(sqlConstraint.FK_Table).Append("] DROP CONSTRAINT [").Append(sqlConstraint.FK_Name).Append(']');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }

                    foreach (var sqlIndex in sqlIndexes)
                    {
                        if (!sqlIndex.Columns.Contains(sqlColumn.Column, StringComparer.OrdinalIgnoreCase) || !droppedIndexes.Add(sqlIndex))
                            continue;
                        _ = sb.Append("DROP INDEX [").Append(sqlIndex.Name).Append("] ON ").Append(table);
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }

                    DropColumnDependents(sql, null, table, sqlColumn.Column);

                    _ = sb.Append("ALTER TABLE ").Append(table).Append(" DROP COLUMN [").Append(sqlColumn.Column).Append(']');
                    sql.Add(sb.ToString());
                    _ = sb.Clear();
                }
            }
        }

        //SQL Server won't alter or drop a column that defaults, check and unique constraints, or statistics made outside the model depend on, these are dropped first and put back after an alter
        private void DropColumnDependents(List<string> sql, List<string>? putBack, string table, string column)
        {
            var objectID = $"OBJECT_ID('{table}')";
            //SQL Server writes the columns in a definition bracketed
            var inDefinition = $"'%[[]{column.Replace("_", "[_]")}]%'";

            foreach (var computed in ExecuteSqlQuery($"SELECT C.name FROM sys.computed_columns C WHERE C.object_id = {objectID} AND C.definition LIKE {inDefinition}"))
                throw new InvalidOperationException($"{nameof(MsSqlEngine)} cannot change {table}.{column} while the computed column {computed} uses it");

            foreach (var row in ExecuteSqlQuery($"SELECT DC.name, DC.definition FROM sys.default_constraints DC JOIN sys.columns C ON C.object_id = DC.parent_object_id AND C.column_id = DC.parent_column_id WHERE DC.parent_object_id = {objectID} AND C.name = '{column}'").Select(x => (IList<object>)x))
            {
                sql.Add($"ALTER TABLE {table} DROP CONSTRAINT [{row[0]}]");
                putBack?.Add($"ALTER TABLE {table} ADD CONSTRAINT [{row[0]}] DEFAULT {row[1]} FOR [{column}]");
            }

            foreach (var row in ExecuteSqlQuery($"SELECT CC.name, CC.definition FROM sys.check_constraints CC WHERE CC.parent_object_id = {objectID} AND CC.definition LIKE {inDefinition}").Select(x => (IList<object>)x))
            {
                sql.Add($"ALTER TABLE {table} DROP CONSTRAINT [{row[0]}]");
                putBack?.Add($"ALTER TABLE {table} WITH CHECK ADD CONSTRAINT [{row[0]}] CHECK {row[1]}");
            }

            var uniqueQuery = $@"SELECT I.name, C.name, IC.is_descending_key, CAST(CASE WHEN I.type = 1 THEN 1 ELSE 0 END AS bit)
FROM sys.indexes I
JOIN sys.index_columns IC ON IC.object_id = I.object_id AND IC.index_id = I.index_id
JOIN sys.columns C ON C.object_id = IC.object_id AND C.column_id = IC.column_id
WHERE I.object_id = {objectID} AND I.is_unique_constraint = 1 AND I.index_id IN (SELECT IC2.index_id FROM sys.index_columns IC2 JOIN sys.columns C2 ON C2.object_id = IC2.object_id AND C2.column_id = IC2.column_id WHERE IC2.object_id = {objectID} AND C2.name = '{column}')
ORDER BY I.name, IC.key_ordinal";
            foreach (var unique in ExecuteSqlQuery(uniqueQuery).Select(x => (IList<object>)x).GroupBy(x => (string)x[0]))
            {
                sql.Add($"ALTER TABLE {table} DROP CONSTRAINT [{unique.Key}]");
                putBack?.Add($"ALTER TABLE {table} ADD CONSTRAINT [{unique.Key}] UNIQUE {((bool)unique.First()[3] ? "CLUSTERED" : "NONCLUSTERED")} ({String.Join(", ", unique.Select(x => $"[{x[1]}] {((bool)x[2] ? "DESC" : "ASC")}"))})");
            }

            var statisticsQuery = $@"SELECT S.name, C.name
FROM sys.stats S
JOIN sys.stats_columns SC ON SC.object_id = S.object_id AND SC.stats_id = S.stats_id
JOIN sys.columns C ON C.object_id = SC.object_id AND C.column_id = SC.column_id
WHERE S.object_id = {objectID} AND S.user_created = 1 AND S.stats_id IN (SELECT SC2.stats_id FROM sys.stats_columns SC2 JOIN sys.columns C2 ON C2.object_id = SC2.object_id AND C2.column_id = SC2.column_id WHERE SC2.object_id = {objectID} AND C2.name = '{column}')
ORDER BY S.name, SC.stats_column_id";
            foreach (var statistics in ExecuteSqlQuery(statisticsQuery).Select(x => (IList<object>)x).GroupBy(x => (string)x[0]))
            {
                sql.Add($"DROP STATISTICS {table}.[{statistics.Key}]");
                putBack?.Add($"CREATE STATISTICS [{statistics.Key}] ON {table}({String.Join(", ", statistics.Select(x => $"[{x[1]}]"))})");
            }
        }

        private void AssureConstraints(bool changeColumns, bool changeConstraints, List<string> sql, ModelDetail model, SqlConstraint[] sqlConstraints, HashSet<string> droppedConstraints, string defaultSchema)
        {
            var constraintNameDictionary = sqlConstraints.Select(x => x.FK_Name).Distinct(StringComparer.OrdinalIgnoreCase).ToDictionary(x => x, x => 0, StringComparer.OrdinalIgnoreCase);

            var sb = new StringBuilder();

            var fkTable = model.DataSourceEntityName;
            var table = model.DataSourceSchemaName is null ? $"[{model.DataSourceEntityName}]" : $"[{model.DataSourceSchemaName}].[{model.DataSourceEntityName}]";

            var usedSqlConstraints = new List<SqlConstraint>();
            foreach (var columnForRelation in model.RelatedNonEnumerableMembers)
            {
                var relatedModelDetails = ModelAnalyzer.GetModel(columnForRelation.ActualType);

                //a key of several members is one constraint of its columns, in the order of the identity referred to

                if (columnForRelation.ForeignIdentities!.Length != relatedModelDetails.IdentityMembers.Count)

                    throw new Exception($"{columnForRelation.Name} names {columnForRelation.ForeignIdentities.Length} foreign identities where {relatedModelDetails.Type.Name} has {relatedModelDetails.IdentityMembers.Count} identities");

                var fkColumns = columnForRelation.ForeignIdentities.Select(x => model.GetMember(x).StoreName).ToArray();

                var pkTable = relatedModelDetails.DataSourceEntityName;
                var pkSchema = relatedModelDetails.DataSourceSchemaName ?? defaultSchema;
                var pkTableQuoted = $"[{pkSchema}].[{pkTable}]";

                var pkColumns = relatedModelDetails.IdentityMembers.Select(x => x.StoreName).ToArray();

                var fkColumn = String.Join("],[", fkColumns);

                var pkColumn = String.Join("],[", pkColumns);


                var constraintColumns = sqlConstraints.Where(x => String.Equals(x.FK_Table, fkTable, StringComparison.OrdinalIgnoreCase) && String.Equals(x.PK_Table, pkTable, StringComparison.OrdinalIgnoreCase) && String.Equals(x.PK_Schema, pkSchema, StringComparison.OrdinalIgnoreCase)).GroupBy(x => x.FK_Name).FirstOrDefault(x => x.Count() == fkColumns.Length && x.Select((column, index) => String.Equals(column.FK_Column, fkColumns[index], StringComparison.OrdinalIgnoreCase) && String.Equals(column.PK_Column, pkColumns[index], StringComparison.OrdinalIgnoreCase)).All(match => match))?.ToArray();

                var sqlConstraint = constraintColumns?[0];
                if (sqlConstraint is null || droppedConstraints.Contains(sqlConstraint.FK_Name))
                {
                    //a new foreign key can fail on the rows, one put back after changing its column can't
                    if (sqlConstraint is null ? changeConstraints : changeColumns || changeConstraints)
                    {
                        var baseConstraintName = $"FK_{fkTable}_{pkTable}";
                        string constraintName;
                        if (sqlConstraint is not null)
                        {
                            constraintName = sqlConstraint.FK_Name;
                        }
                        else if (constraintNameDictionary.TryGetValue(baseConstraintName, out var constraintNameIndex))
                        {
                            constraintNameIndex++;
                            constraintName = baseConstraintName + constraintNameIndex;
                            while (constraintNameDictionary.ContainsKey(constraintName))
                            {
                                constraintNameIndex++;
                                constraintName = baseConstraintName + constraintNameIndex;
                            }
                            constraintNameDictionary[constraintName] = constraintNameIndex;
                        }
                        else
                        {
                            constraintNameDictionary.Add(baseConstraintName, 0);
                            constraintName = baseConstraintName;
                        }
                        _ = sb.Append("ALTER TABLE ").Append(table).Append(" WITH CHECK ADD CONSTRAINT [").Append(constraintName).Append("] FOREIGN KEY ([").Append(fkColumn).Append("]) REFERENCES ").Append(pkTableQuoted).Append("([").Append(pkColumn).Append("])");
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }
                }
                else
                {
                    usedSqlConstraints.AddRange(constraintColumns!);
                }
            }

            if (changeColumns || changeConstraints)
            {
                //foreign keys not in model
                foreach (var sqlConstraint in sqlConstraints.Where(x => String.Equals(x.FK_Table, fkTable, StringComparison.OrdinalIgnoreCase)).GroupBy(x => x.FK_Name).Select(x => x.First()))
                {
                    if (!usedSqlConstraints.Any(x => x.FK_Name == sqlConstraint.FK_Name) && !droppedConstraints.Contains(sqlConstraint.FK_Name))
                    {
                        _ = sb.Append("ALTER TABLE [").Append(sqlConstraint.FK_Schema).Append("].[").Append(sqlConstraint.FK_Table).Append("] DROP CONSTRAINT [").Append(sqlConstraint.FK_Name).Append(']');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }
                }
            }
        }

        private void AssureIndexes(bool changeColumns, bool changeConstraints, List<string> sql, ModelDetail model, SqlIndex[] sqlIndexes, HashSet<SqlIndex> droppedIndexes)
        {
            if (!changeColumns && !changeConstraints)
                return;

            var sb = new StringBuilder();
            var table = model.DataSourceSchemaName is null ? $"[{model.DataSourceEntityName}]" : $"[{model.DataSourceSchemaName}].[{model.DataSourceEntityName}]";

            var usedSqlIndexes = new List<SqlIndex>();
            foreach (var index in model.Indexes)
            {
                var hasFilter = index.IsUnique && index.Members.Any(x => !x.IsDataSourceNotNull);
                var sqlIndex = sqlIndexes.FirstOrDefault(x => String.Equals(x.Name, index.StoreName, StringComparison.OrdinalIgnoreCase));
                var matches = sqlIndex is not null && sqlIndex.IsUnique == index.IsUnique && !sqlIndex.IsClustered && (sqlIndex.FilterDefinition is not null) == hasFilter && sqlIndex.Columns.Count == index.Members.Count;
                for (var i = 0; matches && i < index.Members.Count; i++)
                    matches = String.Equals(sqlIndex!.Columns[i], index.Members[i].StoreName, StringComparison.OrdinalIgnoreCase) && sqlIndex.Descending[i] == index.Descending[i];
                if (sqlIndex is not null && !droppedIndexes.Contains(sqlIndex))
                {
                    usedSqlIndexes.Add(sqlIndex);
                    if (matches)
                        continue;

                    _ = droppedIndexes.Add(sqlIndex);
                    _ = sb.Append("DROP INDEX [").Append(sqlIndex.Name).Append("] ON ").Append(table);
                    sql.Add(sb.ToString());
                    _ = sb.Clear();
                }

                //a new unique index can fail on the rows, one put back after changing a column can't
                if (index.IsUnique && !matches && !changeConstraints)
                    continue;

                _ = sb.Append(index.IsUnique ? "CREATE UNIQUE NONCLUSTERED INDEX [" : "CREATE NONCLUSTERED INDEX [").Append(index.StoreName).Append("] ON ").Append(table).Append('(');
                for (var i = 0; i < index.Members.Count; i++)
                {
                    if (i > 0)
                        _ = sb.Append(", ");
                    _ = sb.Append('[').Append(index.Members[i].StoreName).Append(index.Descending[i] ? "] DESC" : "] ASC");
                }
                _ = sb.Append(')');
                if (hasFilter)
                {
                    //a unique index allows only one null here, the other engines allow many
                    var first = true;
                    foreach (var member in index.Members)
                    {
                        if (member.IsDataSourceNotNull)
                            continue;
                        _ = sb.Append(first ? " WHERE [" : " AND [").Append(member.StoreName).Append("] IS NOT NULL");
                        first = false;
                    }
                }
                sql.Add(sb.ToString());
                _ = sb.Clear();
            }

            //indexes not in model
            foreach (var sqlIndex in sqlIndexes)
            {
                if (usedSqlIndexes.Contains(sqlIndex) || !droppedIndexes.Add(sqlIndex))
                    continue;
                _ = sb.Append("DROP INDEX [").Append(sqlIndex.Name).Append("] ON ").Append(table);
                sql.Add(sb.ToString());
                _ = sb.Clear();
            }
        }

        /// <summary>
        /// Writes the SQL Server column type definition for a model property into the provided <see cref="StringBuilder"/>.
        /// </summary>
        /// <param name="sb">The <see cref="StringBuilder"/> to write the type definition into.</param>
        /// <param name="property">The model property to derive the SQL type from.</param>
        public static void WriteSqlTypeFromModel(StringBuilder sb, ModelMemberDetail property) => WriteSqlTypeFromModel(sb, property, !property.IsDataSourceNotNull);

        private static void WriteSqlTypeFromModel(StringBuilder sb, ModelMemberDetail property, bool nullable)
        {
            var canBeIdentity = false;
            if (property.ColumnCoreType.HasValue)
            {
                switch (property.ColumnCoreType.Value)
                {
                    case CoreType.Boolean:
                    case CoreType.BooleanNullable:
                        _ = sb.Append("[bit]");
                        break;
                    case CoreType.Byte:
                    case CoreType.ByteNullable:
                        _ = sb.Append("[tinyint]");
                        canBeIdentity = true;
                        break;
                    case CoreType.Int16:
                    case CoreType.Int16Nullable:
                        _ = sb.Append("[smallint]");
                        canBeIdentity = true;
                        break;
                    case CoreType.Int32:
                    case CoreType.Int32Nullable:
                        _ = sb.Append("[int]");
                        canBeIdentity = true;
                        break;
                    case CoreType.Int64:
                    case CoreType.Int64Nullable:
                        _ = sb.Append("[bigint]");
                        canBeIdentity = true;
                        break;
                    case CoreType.Single:
                    case CoreType.SingleNullable:
                        _ = sb.Append("[real]");
                        break;
                    case CoreType.Double:
                    case CoreType.DoubleNullable:
                        _ = sb.Append("[float]");
                        break;
                    case CoreType.Decimal:
                    case CoreType.DecimalNullable:
                        _ = sb.Append("[decimal](").Append(property.DataSourcePrecisionLength ?? 19).Append(", ").Append(property.DataSourceScale ?? 5).Append(')');
                        canBeIdentity = property.DataSourceScale == 0;
                        break;
                    case CoreType.Char:
                    case CoreType.CharNullable:
                        _ = sb.Append("[nvarchar](").Append(property.DataSourcePrecisionLength ?? 1).Append(')');
                        break;
                    case CoreType.DateTime:
                    case CoreType.DateTimeNullable:
                        if (property.DatePart == StoreDatePart.Date)
                            _ = sb.Append("[date]");
                        else if (property.DataSourcePrecisionLength.HasValue)
                            _ = sb.Append("[datetime2](").Append(property.DataSourcePrecisionLength.Value).Append(')');
                        else
                            _ = sb.Append("[datetime]");
                        break;
                    case CoreType.DateTimeOffset:
                    case CoreType.DateTimeOffsetNullable:
                        _ = sb.Append("[datetimeoffset](").Append(property.DataSourcePrecisionLength ?? 7).Append(')');
                        break;
                    case CoreType.TimeSpan:
                    case CoreType.TimeSpanNullable:
                        _ = sb.Append("[time](").Append(property.DataSourcePrecisionLength ?? 7).Append(')');
                        break;
                    case CoreType.DateOnly:
                    case CoreType.DateOnlyNullable:
                        _ = sb.Append("[date]");
                        break;
                    case CoreType.TimeOnly:
                    case CoreType.TimeOnlyNullable:
                        _ = sb.Append("[time](").Append(property.DataSourcePrecisionLength ?? 7).Append(')');
                        break;
                    case CoreType.Guid:
                    case CoreType.GuidNullable:
                        _ = sb.Append("[uniqueidentifier]");
                        canBeIdentity = true;
                        break;
                    case CoreType.String:
                        if (property.TextEncoding == StoreTextEncoding.NonUnicode)
                            _ = sb.Append("[varchar](").Append(property.DataSourcePrecisionLength?.ToString() ?? "max").Append(')');
                        else
                            _ = sb.Append("[nvarchar](").Append(property.DataSourcePrecisionLength?.ToString() ?? "max").Append(')');
                        break;
                    default:
                        throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MsSqlEngine)} type.");
                }
            }
            else if (property.Type == typeof(byte[]))
            {
                _ = sb.Append("[varbinary](").Append(property.DataSourcePrecisionLength?.ToString() ?? "max").Append(')');
            }
            else
            {
                throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MsSqlEngine)} type.");
            }

            if (property.IsIdentity && property.IsIdentityAutoGenerated)
            {
                if (!canBeIdentity)
                    throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MsSqlEngine)} {property.Type.Name} {property.Name} cannot be an auto generated identity");
                if (property.CoreType.HasValue && property.CoreType.Value == CoreType.Guid)
                    _ = sb.Append(" DEFAULT NEWID()");
                else
                    _ = sb.Append(" Identity(1,1)");
            }

            if (!nullable) //model checks for identity not null
            {
                _ = sb.Append(" NOT NULL");
                //if (!property.IsIdentityAutoGenerated && allowDefaults)
                //{
                //    _ = sb.Append(" CONSTRAINT DF_");
                //    _ = sb.Append(property.Name);
                //    _ = sb.Append(" DEFAULT ");
                //    WriteDefaultValue(sb, property);
                //}
            }
            else
            {
                _ = sb.Append(" NULL");
            }
        }

        private static void WriteDefaultValue(StringBuilder sb, ModelMemberDetail property)
        {
            if (property.ColumnCoreType.HasValue)
            {
                switch (property.ColumnCoreType.Value)
                {
                    case CoreType.Byte:
                    case CoreType.ByteNullable:
                    case CoreType.SByte:
                    case CoreType.SByteNullable:
                    case CoreType.Int16:
                    case CoreType.Int16Nullable:
                    case CoreType.UInt16:
                    case CoreType.UInt16Nullable:
                    case CoreType.Int32:
                    case CoreType.Int32Nullable:
                    case CoreType.UInt32:
                    case CoreType.UInt32Nullable:
                    case CoreType.Int64:
                    case CoreType.Int64Nullable:
                    case CoreType.UInt64:
                    case CoreType.UInt64Nullable:
                    case CoreType.Single:
                    case CoreType.SingleNullable:
                    case CoreType.Double:
                    case CoreType.DoubleNullable:
                    case CoreType.Decimal:
                    case CoreType.DecimalNullable:
                        _ = sb.Append('0');
                        break;
                    case CoreType.Boolean:
                    case CoreType.BooleanNullable:
                        _ = sb.Append('0');
                        break;
                    case CoreType.Char:
                    case CoreType.CharNullable:
                    case CoreType.String:
                        _ = sb.Append("N'").Append(property.EnumDefaultText?.Replace("'", "''")).Append('\'');
                        break;
                    case CoreType.DateTime:
                    case CoreType.DateTimeNullable:
                    case CoreType.DateOnly:
                    case CoreType.DateOnlyNullable:
                        _ = sb.Append("'1900-01-01'");
                        break;
                    case CoreType.DateTimeOffset:
                    case CoreType.DateTimeOffsetNullable:
                        _ = sb.Append("'1900-01-01 00:00:00 +00:00'");
                        break;
                    case CoreType.TimeSpan:
                    case CoreType.TimeSpanNullable:
                    case CoreType.TimeOnly:
                    case CoreType.TimeOnlyNullable:
                        _ = sb.Append("'00:00:00'");
                        break;
                    case CoreType.Guid:
                    case CoreType.GuidNullable:
                        _ = sb.Append("'00000000-0000-0000-0000-000000000000'");
                        break;
                    default:
                        throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MsSqlEngine)} type.");
                }
            }
            else if (property.Type == typeof(byte[]))
            {
                _ = sb.Append("0x");
            }
            else
            {
                throw new Exception($"Cannot match type {property.Type.Name} to an {nameof(MsSqlEngine)} type.");
            }
        }

        private static void WriteSqlTypeFromColumn(StringBuilder sb, SqlColumnType sqlColumn)
        {
            switch (sqlColumn.DataType)
            {
                case "bit":
                case "tinyint":
                case "smallint":
                case "int":
                case "bigint":
                case "real":
                case "float":
                case "smallmoney":
                case "money":
                case "date":
                case "smalldatetime":
                case "datetime":
                case "timestamp":
                case "rowversion":
                case "text":
                case "ntext":
                case "image":
                case "uniqueidentifier":
                case "xml":
                case "sql_variant":
                    _ = sb.Append(sqlColumn.DataType);
                    break;
                case "numeric":
                case "decimal":
                    _ = sb.Append(sqlColumn.DataType).Append('(').Append(sqlColumn.NumericPrecision ?? 0).Append(", ").Append(sqlColumn.NumericScale ?? 0).Append(')');
                    break;
                case "datetime2":
                case "datetimeoffset":
                case "time":
                    _ = sb.Append(sqlColumn.DataType).Append('(').Append(sqlColumn.DatetimePrecision ?? 0).Append(')');
                    break;
                case "varchar":
                case "nvarchar":
                case "char":
                case "nchar":
                case "binary":
                case "varbinary":
                    _ = sb.Append(sqlColumn.DataType).Append('(').Append(!sqlColumn.CharacterMaximumLength.HasValue || sqlColumn.CharacterMaximumLength.Value == -1 ? "max" : sqlColumn.CharacterMaximumLength.Value.ToString()).Append(')');
                    break;
                default:
                    throw new NotImplementedException($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(MsSqlEngine)} type {sqlColumn.DataType} not implemented.");
            }
        }

        private static bool ModelMatchesSqlType(ModelMemberDetail property, SqlColumnType sqlColumn)
        {
            if (sqlColumn.IsPrimaryKey != property.IsIdentity || sqlColumn.IsAutoGenerated != property.IsIdentityAutoGenerated)
                return false;

            if (property.ColumnCoreType.HasValue)
            {
                switch (property.ColumnCoreType.Value)
                {
                    case CoreType.Boolean: return sqlColumn.DataType == "bit" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Byte: return sqlColumn.DataType == "tinyint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int16: return sqlColumn.DataType == "smallint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int32: return sqlColumn.DataType == "int" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
                    case CoreType.Int64: return sqlColumn.DataType == "bigint" && sqlColumn.IsNullable == !property.IsDataSourceNotNull;
