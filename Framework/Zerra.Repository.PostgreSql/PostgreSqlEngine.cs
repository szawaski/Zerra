        private bool AssureTable(bool create, List<string> sql, bool needCreateDatabase, ModelDetail model)
        {
            var table = model.DataSourceSchemaName is null ? model.DataSourceEntityName.ToLower() : $"{model.DataSourceSchemaName.ToLower()}.{model.DataSourceEntityName.ToLower()}";
            var nonIdentityColumns = model.Members.Where(x => !x.IsIdentity && !x.IsDataSourceEntity && x.ColumnCoreType.HasValue || x.Type == typeof(byte[])).ToArray();
            var identityColumns = model.Members.Where(x => x.IsIdentity).ToArray();

            if (nonIdentityColumns.Length + identityColumns.Length == 0)
                return false; //Cannot create table with no columns

            if (!needCreateDatabase)
            {
                var sqlQuery = $"SELECT COUNT(1) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME = '{model.DataSourceEntityName.ToLower()}' AND TABLE_SCHEMA = {(model.DataSourceSchemaName is null ? "current_schema()" : $"'{model.DataSourceSchemaName.ToLower()}'")}";
                var exists = ExecuteSqlScalar<long>(sqlQuery) > 0;
                if (exists)
                    return false;
            }

            if (create)
            {
                var sb = new StringBuilder();
                _ = sb.Append("CREATE TABLE ").Append(table).Append("(\r\n");

                for (var i = 0; i < identityColumns.Length; i++)
                {
                    var property = identityColumns[i];
                    if (i > 0)
                        _ = sb.Append(",\r\n");
                    _ = sb.Append('\t').Append(property.StoreName).Append(' ');
                    WriteSqlTypeFromModel(sb, property);
                    WriteTypeEndingFromModel(sb, property);
                }
                for (var i = 0; i < nonIdentityColumns.Length; i++)
                {
                    var property = nonIdentityColumns[i];
                    if (i > 0 || identityColumns.Length > 0)
                        _ = sb.Append(",\r\n");
                    _ = sb.Append('\t').Append(property.StoreName).Append(' ');
                    WriteSqlTypeFromModel(sb, property);
                    WriteTypeEndingFromModel(sb, property);
                }
                if (identityColumns.Length > 0)
                {
                    if (identityColumns.Length > 0 || nonIdentityColumns.Length > 0)
                        _ = sb.Append(',');
                    _ = sb.Append("\r\n\tCONSTRAINT PK_").Append(model.DataSourceEntityName).Append(" PRIMARY KEY(\r\n");

                    for (var i = 0; i < identityColumns.Length; i++)
                    {
                        var property = identityColumns[i];
                        if (i > 0)
                            _ = sb.Append(",\r\n");
                        _ = sb.Append("\t\t").Append(property.StoreName);
                    }
                    _ = sb.Append("\r\n\t)\r\n");
                }
                _ = sb.Append("\r\n)");

                sql.Add(sb.ToString());
            }
            return true;
        }

        private void AssureColumns(bool changeColumns, bool changeConstraints, bool dropColumns, List<string> sql, ModelDetail model, SqlColumnType[] sqlColumns, SqlConstraint[] sqlConstraints, HashSet<string> droppedConstraints, SqlIndex[] sqlIndexes, HashSet<SqlIndex> droppedIndexes)
        {
            var table = model.DataSourceSchemaName is null ? model.DataSourceEntityName.ToLower() : $"{model.DataSourceSchemaName.ToLower()}.{model.DataSourceEntityName.ToLower()}";
            var columns = model.Members.Where(x => !x.IsDataSourceEntity && x.ColumnCoreType.HasValue || x.Type == typeof(byte[])).ToArray();

            var sb = new StringBuilder();

            foreach (var column in columns)
            {
                var sqlColumn = sqlColumns.FirstOrDefault(x => x.Table == model.DataSourceEntityName.ToLower() && x.Column == column.StoreName.ToLower());
                if (sqlColumn is null)
                {
                    if (changeColumns)
                    {
                        //without constraints a new column is nullable until they run, so the code writing the table before it still can
                        var nullable = !changeConstraints && !column.IsIdentity;
                        _ = sb.Append("ALTER TABLE ").Append(table).Append(" ADD ").Append(column.StoreName).Append(' ');
                        WriteSqlTypeFromModel(sb, column);
                        WriteTypeEndingFromModel(sb, column, nullable || !column.IsDataSourceNotNull);
                        var withDefault = !nullable && column.IsDataSourceNotNull && !column.IsIdentityAutoGenerated;
                        if (withDefault)
                        {
                            _ = sb.Append(" DEFAULT ");
                            WriteDefaultValue(sb, column);
                        }
                        _ = sb.Append(';');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                        if (withDefault)
                        {
                            _ = sb.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN ").Append(column.StoreName.ToLower()).Append(" DROP DEFAULT;");
                            sql.Add(sb.ToString());
                            _ = sb.Clear();
                        }
                    }
                }
                else
                {
                    if (changeColumns || changeConstraints)
                    {
                        var sameType = ModelMatchesSqlType(column, sqlColumn);
                        if (!sameType)
                        {
                            if (sqlColumn.IsPrimaryKey || sqlColumn.IsAutoGenerated || sqlColumn.IsPrimaryKey != column.IsIdentity || sqlColumn.IsAutoGenerated != column.IsIdentityAutoGenerated)
                                throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(PostgreSqlEngine)} cannot automatically change column with a Primary Key or Identity {model.Type.Name}.{column.Name}");

                            //columns alone only widen a type and allow nulls, changes that never fail on the rows
                            var nullable = !column.IsDataSourceNotNull;
                            var changeType = !ModelMatchesSqlType(column, sqlColumn.WithNullable(nullable));
                            if (changeType && !ModelRelatesToSqlType(column, sqlColumn))
                                throw new InvalidOperationException($"{nameof(PostgreSqlEngine)} cannot change {model.Type.Name}.{column.Name} from {sqlColumn.DataType} to an unrelated type, add a new column and move the data instead");
                            if (!changeConstraints)
                            {
                                if (changeType && !ModelWidensSqlType(column, sqlColumn))
                                    continue;
                                nullable = nullable || sqlColumn.IsNullable;
                            }
                            if (!changeType && nullable == sqlColumn.IsNullable)
                                continue;

                            var theseSqlConstraints = sqlConstraints.Where(x => (x.PK_Table == model.DataSourceEntityName.ToLower() && x.PK_Column == column.Name) || (x.FK_Table == model.DataSourceEntityName && x.FK_Column == column.Name)).ToArray();
                            if (theseSqlConstraints.Length > 0)
                            {
                                foreach (var sqlConstraint in theseSqlConstraints)
                                {
                                    if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                                        continue;
                                    _ = sb.Append("ALTER TABLE ").Append(sqlConstraint.FK_Schema).Append('.').Append(sqlConstraint.FK_Table.ToLower()).Append(" DROP CONSTRAINT ").Append(sqlConstraint.FK_Name.ToLower()).Append(';');
                                    sql.Add(sb.ToString());
                                    _ = sb.Clear();
                                }
                            }

                            if (changeType)
                            {
                                _ = sb.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN ").Append(column.StoreName.ToLower()).Append(" TYPE ");
                                WriteSqlTypeFromModel(sb, column);
                                _ = sb.Append(';');
                                sql.Add(sb.ToString());
                                _ = sb.Clear();
                            }

                            if (nullable != sqlColumn.IsNullable)
                            {
                                _ = sb.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN ").Append(column.StoreName.ToLower()).Append(nullable ? " DROP NOT NULL;" : " SET NOT NULL;");
                                sql.Add(sb.ToString());
                                _ = sb.Clear();
                            }
                        }
                    }
                }
            }

            if (dropColumns || changeColumns)
            {
                //columns not in model, a column has a row for each key it is in
                var droppedColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                foreach (var sqlColumn in sqlColumns.Where(x => x.Table == model.DataSourceEntityName.ToLower()))
                {
                    var column = columns.FirstOrDefault(x => x.StoreName.ToLower() == sqlColumn.Column);
                    if (column is not null || !droppedColumns.Add(sqlColumn.Column))
                        continue;

                    if (!dropColumns)
                    {
                        //kept until dropped, nullable so the code without it can write the table
                        if (sqlColumn.IsNullable)
                            continue;
                        if (sqlColumns.Any(x => x.Table == sqlColumn.Table && x.Column == sqlColumn.Column && (x.IsPrimaryKey || x.IsAutoGenerated)))
                            throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(PostgreSqlEngine)} needs to make {sqlColumn.Table}.{sqlColumn.Column} nullable but cannot automatically change column with a Primary Key or Identity");

                        _ = sb.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN ").Append(sqlColumn.Column.ToLower()).Append(" DROP NOT NULL;");
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                        continue;
                    }

                    if (sqlColumns.Any(x => x.Table == sqlColumn.Table && x.Column == sqlColumn.Column && x.IsPrimaryKey))
                        throw new Exception($"{nameof(ITransactStoreEngine.BuildStoreGenerationPlan)} {nameof(PostgreSqlEngine)} cannot automatically drop {sqlColumn.Table}.{sqlColumn.Column} in the Primary Key");

                    var theseSqlConstraints = sqlConstraints.Where(x => (x.PK_Table == sqlColumn.Table && x.PK_Column == sqlColumn.Column) || (x.FK_Table == sqlColumn.Table && x.FK_Column == sqlColumn.Column)).ToArray();
                    foreach (var sqlConstraint in theseSqlConstraints)
                    {
                        if (!droppedConstraints.Add(sqlConstraint.FK_Name))
                            continue;
                        _ = sb.Append("ALTER TABLE ").Append(sqlConstraint.FK_Schema).Append('.').Append(sqlConstraint.FK_Table.ToLower()).Append(" DROP CONSTRAINT ").Append(sqlConstraint.FK_Name.ToLower()).Append(';');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }

                    foreach (var sqlIndex in sqlIndexes)
                    {
                        if (!sqlIndex.Columns.Contains(sqlColumn.Column, StringComparer.OrdinalIgnoreCase) || !droppedIndexes.Add(sqlIndex))
                            continue;
                        _ = sb.Append("DROP INDEX ").Append(model.DataSourceSchemaName is null ? null : model.DataSourceSchemaName.ToLower() + ".").Append('"').Append(sqlIndex.Name).Append("\";");
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }

                    _ = sb.Append("ALTER TABLE ").Append(table).Append(" DROP COLUMN ").Append(sqlColumn.Column.ToLower()).Append(';');
                    sql.Add(sb.ToString());
                    _ = sb.Clear();
                }
            }
        }

        private void AssureConstraints(bool changeColumns, bool changeConstraints, List<string> sql, ModelDetail model, SqlConstraint[] sqlConstraints, HashSet<string> droppedConstraints, string defaultSchema)
        {
            var table = model.DataSourceSchemaName is null ? model.DataSourceEntityName.ToLower() : $"{model.DataSourceSchemaName.ToLower()}.{model.DataSourceEntityName.ToLower()}";
            var constraintNameDictionary = sqlConstraints.Select(x => x.FK_Name).Distinct(StringComparer.OrdinalIgnoreCase).ToDictionary(x => x, x => 0, StringComparer.OrdinalIgnoreCase);

            var sb = new StringBuilder();

            var fkTable = model.DataSourceEntityName;

            var usedSqlConstraints = new List<SqlConstraint>();
            foreach (var columnForRelation in model.RelatedNonEnumerableMembers)
            {
                var relatedModelDetails = ModelAnalyzer.GetModel(columnForRelation.ActualType);

                if (columnForRelation.ForeignIdentities is null)
                    throw new Exception($"{columnForRelation.Type.Name} missing Foreign Identity");

                //a key of several members is one constraint of its columns, in the order of the identity referred to

                if (columnForRelation.ForeignIdentities!.Length != relatedModelDetails.IdentityMembers.Count)

                    throw new Exception($"{columnForRelation.Name} names {columnForRelation.ForeignIdentities.Length} foreign identities where {relatedModelDetails.Type.Name} has {relatedModelDetails.IdentityMembers.Count} identities");

                var fkColumns = columnForRelation.ForeignIdentities.Select(x => model.GetMember(x).StoreName).ToArray();

                var pkTable = relatedModelDetails.DataSourceEntityName;
                var pkSchema = relatedModelDetails.DataSourceSchemaName?.ToLower() ?? defaultSchema;

                var pkColumns = relatedModelDetails.IdentityMembers.Select(x => x.StoreName).ToArray();

                var fkColumn = String.Join(",", fkColumns);

                var pkColumn = String.Join(",", pkColumns);


                var constraintColumns = sqlConstraints.Where(x => String.Equals(x.FK_Table, fkTable, StringComparison.OrdinalIgnoreCase) && String.Equals(x.PK_Table, pkTable, StringComparison.OrdinalIgnoreCase) && String.Equals(x.PK_Schema, pkSchema, StringComparison.OrdinalIgnoreCase)).GroupBy(x => x.FK_Name).FirstOrDefault(x => x.Count() == fkColumns.Length && x.Select((column, index) => String.Equals(column.FK_Column, fkColumns[index], StringComparison.OrdinalIgnoreCase) && String.Equals(column.PK_Column, pkColumns[index], StringComparison.OrdinalIgnoreCase)).All(match => match))?.ToArray();

                var sqlConstraint = constraintColumns?[0];
                if (sqlConstraint is null || droppedConstraints.Contains(sqlConstraint.FK_Name))
                {
                    //a new foreign key can fail on the rows, one put back after changing its column can't
                    if (sqlConstraint is null ? changeConstraints : changeColumns || changeConstraints)
                    {
                        var baseConstraintName = $"FK_{fkTable}_{pkTable}";
                        string constraintName;
                        if (sqlConstraint is not null)
                        {
                            constraintName = sqlConstraint.FK_Name;
                        }
                        else if (constraintNameDictionary.TryGetValue(baseConstraintName, out var constraintNameIndex))
                        {
                            constraintNameIndex++;
                            constraintName = baseConstraintName + constraintNameIndex;
                            while (constraintNameDictionary.ContainsKey(constraintName))
                            {
                                constraintNameIndex++;
                                constraintName = baseConstraintName + constraintNameIndex;
                            }
                            constraintNameDictionary[constraintName] = constraintNameIndex;
                        }
                        else
                        {
                            constraintNameDictionary.Add(baseConstraintName, 0);
                            constraintName = baseConstraintName;
                        }
                        _ = sb.Append("ALTER TABLE ").Append(table).Append(" ADD CONSTRAINT ").Append(constraintName).Append(" FOREIGN KEY (").Append(fkColumn.ToLower()).Append(") REFERENCES ").Append(pkSchema).Append('.').Append(pkTable.ToLower()).Append('(').Append(pkColumn.ToLower()).Append(");");
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }
                }
                else
                {
                    usedSqlConstraints.AddRange(constraintColumns!);
                }
            }

            if (changeColumns || changeConstraints)
            {
                //foreign keys not in model
                foreach (var sqlConstraint in sqlConstraints.Where(x => String.Equals(x.FK_Table, fkTable, StringComparison.OrdinalIgnoreCase)).GroupBy(x => x.FK_Name).Select(x => x.First()))
                {
                    if (!usedSqlConstraints.Any(x => x.FK_Name == sqlConstraint.FK_Name) && !droppedConstraints.Contains(sqlConstraint.FK_Name))
                    {
                        _ = sb.Append("ALTER TABLE ").Append(sqlConstraint.FK_Schema).Append('.').Append(sqlConstraint.FK_Table.ToLower()).Append(" DROP CONSTRAINT ").Append(sqlConstraint.FK_Name.ToLower()).Append(';');
                        sql.Add(sb.ToString());
                        _ = sb.Clear();
                    }
                }
            }
        }

        private void AssureIndexes(bool changeColumns, bool changeConstraints, List<string> sql, ModelDetail model, SqlIndex[] sqlIndexes, HashSet<SqlIndex> droppedIndexes)
        {
            var table = model.DataSourceSchemaName is null ? model.DataSourceEntityName.ToLower() : $"{model.DataSourceSchemaName.ToLower()}.{model.DataSourceEntityName.ToLower()}";
            if (!changeColumns && !changeConstraints)
                return;

            var sb = new StringBuilder();

            var usedSqlIndexes = new List<SqlIndex>();
            foreach (var index in model.Indexes)
            {
                var sqlIndex = sqlIndexes.FirstOrDefault(x => String.Equals(x.Name, index.StoreName, StringComparison.OrdinalIgnoreCase));
                if (sqlIndex is not null && !droppedIndexes.Contains(sqlIndex))
                {
                    usedSqlIndexes.Add(sqlIndex);
                    var matches = sqlIndex.IsUnique == index.IsUnique && sqlIndex.Columns.Count == index.Members.Count;
                    for (var i = 0; matches && i < index.Members.Count; i++)
                        matches = String.Equals(sqlIndex.Columns[i], index.Members[i].StoreName, StringComparison.OrdinalIgnoreCase) && sqlIndex.Descending[i] == index.Descending[i];
                    if (matches)
                        continue;

                    _ = sb.Append("DROP INDEX ").Append(model.DataSourceSchemaName is null ? null : model.DataSourceSchemaName.ToLower() + ".").Append('"').Append(sqlIndex.Name).Append("\";");
                    sql.Add(sb.ToString());
                    _ = sb.Clear();
                }

                //a new unique index can fail on the rows
                if (index.IsUnique && !changeConstraints)
                    continue;

                _ = sb.Append(index.IsUnique ? "CREATE UNIQUE INDEX " : "CREATE INDEX ").Append(index.StoreName.ToLower()).Append(" ON ").Append(table).Append('(');
                for (var i = 0; i < index.Members.Count; i++)
                {
                    if (i > 0)
                        _ = sb.Append(", ");
                    _ = sb.Append(index.Members[i].StoreName.ToLower());
                    if (index.Descending[i])
                        _ = sb.Append(" DESC");
                }
                _ = sb.Append(");");
                sql.Add(sb.ToString());
                _ = sb.Clear();
            }

            //indexes not in model
            foreach (var sqlIndex in sqlIndexes)
            {
                if (usedSqlIndexes.Contains(sqlIndex) || !droppedIndexes.Add(sqlIndex))
                    continue;
                _ = sb.Append("DROP INDEX ").Append(model.DataSourceSchemaName is null ? null : model.DataSourceSchemaName.ToLower() + ".").Append('"').Append(sqlIndex.Name).Append("\";");
                sql.Add(sb.ToString());
                _ = sb.Clear();
            }
        }

