                    {
                        var sql = GenerateSqlInsertMany<TModel>(models, ref index, graph, modelDetail);
                        using (var command = connection.CreateCommand(local))
                        {
                            command.CommandTimeout = 0;
                            command.CommandText = sql;
                            rowsAffected += await command.ExecuteNonQueryAsync(cancellationToken);
                        }
                    }
                    if (local is not null && rowsAffected == models.Length)
                        await local.CommitAsync(cancellationToken);
                }
                finally
                {
                    if (local is not null)
                        await local.DisposeAsync();
                }
            }
            return rowsAffected;
        }
