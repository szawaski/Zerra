namespace Zerra.Repository
{
    /// <summary>
    /// A column read from a data store, as the member type and <see cref="StorePropertiesAttribute"/> values code-first would write it from.
    /// </summary>
    public sealed class DataStoreSchemaColumn
    {
        /// <summary>The column name in the data store.</summary>
        public string Name { get; }
        /// <summary>The member type without <see cref="Nullable{T}"/>, such as <see cref="int"/>, <see cref="string"/>, or <see cref="T:byte[]"/>, and <see cref="object"/> when no member type can hold the column.</summary>
        public Type Type { get; }
        /// <summary>The column can't hold null.</summary>
        public bool NotNull { get; }
        /// <summary>The column is part of the primary key.</summary>
        public bool IsIdentity { get; }
        /// <summary>The data store generates the value, such as an identity or a generated GUID.</summary>
        public bool IsAutoGenerated { get; }
        /// <summary>How text is stored.</summary>
        public StoreTextEncoding TextEncoding { get; }
        /// <summary>The part of a date and time that is stored.</summary>
        public StoreDatePart DatePart { get; }
        /// <summary>The precision or length, null for the engine's default.</summary>
        public int? PrecisionLength { get; }
        /// <summary>The scale, null for the engine's default.</summary>
        public int? Scale { get; }
        /// <summary>The column's type as the data store names it.</summary>
        public string StoreType { get; }
        /// <summary>Why the member doesn't match the column exactly, such as a type code-first would write differently, null when it matches.</summary>
        public string? Note { get; }

        /// <summary>
        /// Creates a column.
        /// </summary>
        /// <param name="name">The column name in the data store.</param>
        /// <param name="type">The member type without <see cref="Nullable{T}"/>.</param>
        /// <param name="notNull">The column can't hold null.</param>
        /// <param name="isIdentity">The column is part of the primary key.</param>
        /// <param name="isAutoGenerated">The data store generates the value.</param>
        /// <param name="textEncoding">How text is stored.</param>
        /// <param name="datePart">The part of a date and time that is stored.</param>
        /// <param name="precisionLength">The precision or length, null for the engine's default.</param>
        /// <param name="scale">The scale, null for the engine's default.</param>
        /// <param name="storeType">The column's type as the data store names it.</param>
        /// <param name="note">Why the member doesn't match the column exactly, null when it matches.</param>
        public DataStoreSchemaColumn(string name, Type type, bool notNull, bool isIdentity, bool isAutoGenerated, StoreTextEncoding textEncoding, StoreDatePart datePart, int? precisionLength, int? scale, string storeType, string? note)
        {
            this.Name = name;
            this.Type = type;
            this.NotNull = notNull;
            this.IsIdentity = isIdentity;
            this.IsAutoGenerated = isAutoGenerated;
            this.TextEncoding = textEncoding;
            this.DatePart = datePart;
            this.PrecisionLength = precisionLength;
            this.Scale = scale;
            this.StoreType = storeType;
            this.Note = note;
        }

        /// <inheritdoc />
        public override string ToString() => $"{Name} {StoreType}";
    }
}
